/**
 * SDD-60 §3.10 — what the built-in packages keep generated from their own `.fudapi`, in step
 * with the emitter: `impl/fudic.d.ts`, which types their implementations, and the modules their
 * tests evaluate those implementations against (`test/generated/*.ts`).
 *
 * The packages cannot run the emitter themselves (`@fudic/api` depends on them for its tests),
 * so the files are committed and this test fails when one falls behind. To rewrite them:
 * `FUDIC_UPDATE_GENERATED=1 pnpm --filter @fudic/api test built-ins`.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { createApiIndex, emitDeclarations, emitModule, parseApi, type ApiSource, type Side } from '../../src/index.js';

const UPDATE = process.env['FUDIC_UPDATE_GENERATED'] === '1';

/** A built-in package, as an app finds it among its dependencies. */
function sources(pkg: string): { readonly root: string; readonly sources: readonly ApiSource[] } {
  const root = fileURLToPath(new URL(`../../node_modules/${pkg}/`, import.meta.url));
  const names = readdirSync(`${root}fudapi`).filter((n) => n.endsWith('.fudapi')).sort();
  return {
    root,
    sources: names.map((name) => {
      const path = `${root}fudapi/${name}`;
      const result = parseApi(readFileSync(path, 'utf8'));
      expect(result.diagnostics, path).toEqual([]);
      return { id: `${pkg}/${name.slice(0, -'.fudapi'.length)}`, path, file: result.value, origin: { package: pkg } };
    }),
  };
}

const HEADER =
  "// The types of this package's own `.fudapi`, as `emitDeclarations` writes them. Regenerated by\n" +
  '// a test of @fudic/api, which fails when they fall behind.\n';

/** Compares a committed file with what the emitter writes now, or rewrites it. */
function inStep(path: string, expected: string): void {
  if (UPDATE) writeFileSync(path, expected);
  expect(readFileSync(path, 'utf8'), `${path} fell behind: rerun with FUDIC_UPDATE_GENERATED=1`).toBe(expected);
}

const PACKAGES: readonly (readonly [pkg: string, modules: readonly (readonly [id: string, side: Side])[]])[] = [
  [
    '@fudic/forms',
    [
      ['@fudic/forms/rules', 'browser'],
      ['@fudic/forms/patterns', 'browser'],
    ],
  ],
  [
    '@fudic/http',
    [
      ['@fudic/http/middlewares', 'browser'],
      ['@fudic/http/middlewares', 'server'],
    ],
  ],
];

describe('the built-ins keep their generated files in step (§3.10)', () => {
  for (const [pkg, modules] of PACKAGES) {
    it(`${pkg}: impl/fudic.d.ts and test/generated/`, () => {
      const { root, sources: own } = sources(pkg);
      const index = createApiIndex(own);
      inStep(`${root}impl/fudic.d.ts`, HEADER + own.map((s) => emitDeclarations(s, index, {})).join(''));
      for (const [id, side] of modules) {
        const source = own.find((s) => s.id === id)!;
        const name = id.slice(pkg.length + 1);
        inStep(`${root}test/generated/${name}.${side}.ts`, emitModule(source, index, {}, side));
      }
    });
  }
});
