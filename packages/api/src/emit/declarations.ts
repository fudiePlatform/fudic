/**
 * `emitDeclarations` (SDD-60 §3.11): the `.d.ts` of a `.fudapi`, `declare module 'fudic:<id>'`,
 * what the TypeScript of the editor and fudic's typecheck read in the developer's files.
 *
 * Deterministic: the same index gives the same bytes. A name of another file is reached as
 * `import('fudic:<its id>').Name`, so the block needs no import of its own beyond the two
 * contract entries, and only the names it uses.
 */

import type { Decl, EnumDecl, FailsClause, FnDecl, FormDecl, LayoutDecl, LoadDecl, MiddlewareDecl, PathsDecl, PatternDecl, PipeDecl, RuleDecl, TypeDecl } from '../ast.js';
import type { ApiIndex, ApiSource } from '../index-api.js';
import type { ApiContext } from '../validate.js';
import { schemaType, valueType } from './form.js';
import { borrowedForms, effective, fieldsType, jsdoc, middlewaresOf, pageParams, pascal, camel, projectRef, str, tsType, type EmitCtx } from './shared.js';

interface DeclCtx extends EmitCtx {
  readonly api: ApiContext;
  /** Names of `@fudic/http/contract` used. */
  readonly http: Set<string>;
  /** Names of `@fudic/forms/contract` used. */
  readonly forms: Set<string>;
  /** Names of `@fudic/core` used: `Pipe`, for a pipe (SDD-71). */
  readonly core: Set<string>;
}

const I = '  ';

export function emitDeclarations(source: ApiSource, index: ApiIndex, api: ApiContext): string {
  const c: DeclCtx = {
    source,
    index,
    api,
    ref: (other, name) => `import(${str(`fudic:${other.id}`)}).${name}`,
    http: new Set(),
    forms: new Set(),
    core: new Set(),
  };
  const body = source.file.declarations.map((d) => declaration(d, c)).filter((s) => s !== '');
  for (const [other, names] of borrowedForms(c)) {
    const all = names.flatMap((n) => [n, `${pascal(n)}Value`]);
    body.push(`${I}export { ${all.join(', ')} } from ${str(`fudic:${other.id}`)};`);
  }
  const imports = [
    ...(c.http.size > 0 ? [`${I}import type { ${[...c.http].sort().join(', ')} } from '@fudic/http/contract';`] : []),
    ...(c.forms.size > 0 ? [`${I}import type { ${[...c.forms].sort().join(', ')} } from '@fudic/forms/contract';`] : []),
    ...(c.core.size > 0 ? [`${I}import type { ${[...c.core].sort().join(', ')} } from '@fudic/core';`] : []),
  ];
  const parts = [imports.join('\n'), ...body].filter((s) => s !== '');
  return `// Generated by fudic from ${source.id}.fudapi. Do not edit.\ndeclare module ${str(`fudic:${source.id}`)} {\n${parts.join('\n\n')}\n}\n`;
}

function declaration(d: Decl, c: DeclCtx): string {
  const doc = jsdoc(d.doc, I);
  switch (d.kind) {
    case 'type':
      return doc + typeDecl(d, c);
    case 'enum':
      return doc + enumDecl(d);
    case 'pattern':
      return doc + patternDecl(d);
    case 'rule':
      return doc + ruleDecl(d, c);
    case 'middleware':
      return doc + middlewareDecl(d, c);
    case 'pipe':
      return pipeDecl(d, doc, c);
    case 'form':
      return doc + formDecl(d, c);
    case 'load':
      return doc + loadDecl(d, c);
    case 'paths':
      return doc + pathsDecl(d, c);
    case 'layout':
      return doc + layoutDecl(d, c);
    case 'fn':
      return doc + fnDecl(d, c);
    default:
      return '';
  }
}

function typeDecl(d: TypeDecl, c: DeclCtx): string {
  const fields = fieldsType(d.fields, c);
  return `${I}export interface ${d.name.text} ${fields}`;
}

const enumDecl = (d: EnumDecl): string => `${I}export type ${d.name.text} = ${d.members.map((m) => str(m.text).replace(/"/gu, "'")).join(' | ')};`;

const patternDecl = (d: PatternDecl): string => `${I}export const ${camel(d.name.text)}: RegExp;`;

/** `{ readonly reserved: () => HttpError }` of a list of `fails`. */
function failsType(fails: readonly FailsClause[], c: DeclCtx): string {
  c.http.add('HttpError');
  return `{ ${fails.map((f) => `readonly ${camel(f.code.text)}: () => HttpError`).join('; ')} }`;
}

/** The value a rule's `on field` takes. */
function ruleValue(d: RuleDecl, c: DeclCtx): string {
  if (d.on === undefined || d.on.target.text !== 'field') return 'Readonly<Record<string, unknown>>';
  const types = d.on.types.map((t) => {
    if (t.kind === 'named' && t.name.text === '*') return 'unknown';
    if (t.kind === 'list' && t.element.kind === 'named' && t.element.name.text === '*') return 'readonly unknown[]';
    const ts = tsType(t, c);
    return ts === 'number' || ts === 'Date' ? `${ts} | null` : ts;
  });
  return [...new Set(types)].join(' | ');
}

function ruleDecl(d: RuleDecl, c: DeclCtx): string {
  c.forms.add('Rule');
  c.forms.add('Check');
  const name = camel(d.name.text);
  const params = fieldsType(d.params, c);
  const codes = d.fails.length > 1 ? d.fails.map((f) => `'${f.code.text}'`).join(' | ') : 'never';
  const runs = d.runs?.value.text;
  if (runs !== 'server' && runs !== 'remote') {
    const args = `${ruleValue(d, c)}, ${params}, ${codes}`;
    return `${I}export const ${name}: Rule<${args}>;\n${I}export type ${pascal(d.name.text)}Check = Check<${args}>;`;
  }
  // A rule the server runs is given the server's `ctx`, with what its middlewares add (SDD-80 §3.2).
  c.http.add('ServerContext');
  const prefix = pascal(d.name.text);
  const args = `${ruleValue(d, c)}, ${params}, ${codes}, ${prefix}Ctx`;
  return [
    `${I}export type ${prefix}Ctx = ServerContext${addsOf(d, c)};`,
    `${I}export const ${name}: Rule<${args}>;`,
    `${I}export type ${prefix}Check = Check<${args}>;`,
  ].join('\n');
}

/**
 * A pipe (SDD-71 §3.3): `<N>Args` when it has parameters, `<N>Format`, and the value whose
 * `implement` binds the implementation. The documentation goes on the value, which is what the
 * view imports and hovers. Without `on` its value is `unknown`: `FUD1340` already said why.
 */
function pipeDecl(d: PipeDecl, doc: string, c: DeclCtx): string {
  c.core.add('Pipe');
  const name = camel(d.name.text);
  const prefix = pascal(d.name.text);
  const value = d.on === undefined ? 'unknown' : [...new Set(d.on.types.map((t) => tsType(t, c)))].join(' | ');
  const out: string[] = [];
  if (d.params.length > 0) {
    out.push(`${I}export interface ${prefix}Args ${fieldsType(d.params, c)}`);
    out.push(`${I}export type ${prefix}Format = (value: ${value}, args: ${prefix}Args, locale: string) => string;`);
    out.push(`${doc}${I}export const ${name}: { implement(format: ${prefix}Format): (args: ${prefix}Args) => Pipe<${value}> };`);
  } else {
    out.push(`${I}export type ${prefix}Format = (value: ${value}, locale: string) => string;`);
    out.push(`${doc}${I}export const ${name}: { implement(format: ${prefix}Format): Pipe<${value}> };`);
  }
  return out.join('\n');
}

function middlewareDecl(d: MiddlewareDecl, c: DeclCtx): string {
  c.http.add('MiddlewarePiece');
  const prefix = pascal(d.name.text);
  const params = fieldsType(d.params, c);
  const adds = d.adds === undefined ? '{}' : `${prefix}Adds`;
  const omit = [...(d.client === undefined ? ["'client'"] : []), ...(d.server === undefined ? ["'server'"] : [])];
  const piece = `MiddlewarePiece<${params}, ${adds}>`;
  const lines = [
    ...(d.adds === undefined ? [] : [`${I}export interface ${prefix}Adds ${fieldsType(d.adds.fields, c)}`]),
    `${I}export const ${camel(d.name.text)}: ${omit.length === 0 ? piece : `Omit<${piece}, ${omit.join(' | ')}>`};`,
  ];
  if (d.client !== undefined) {
    c.http.add('ClientHalf');
    lines.push(`${I}export type ${prefix}Client = ClientHalf<${params}>;`);
  }
  if (d.server !== undefined) {
    c.http.add('ServerHalf');
    lines.push(`${I}export type ${prefix}Server = ServerHalf<${params}, ${adds}>;`);
  }
  if (d.fails.length > 0) lines.push(`${I}export const ${prefix}Fails: ${failsType(d.fails, c)};`);
  return lines.join('\n');
}

function formDecl(d: FormDecl, c: DeclCtx): string {
  return `${I}export const ${d.name.text}: ${schemaType(d.fields, c, c.forms)};\n${I}export type ${pascal(d.name.text)}Value = ${valueType(d.fields, c)};`;
}

/** What the `use`s a level ends up with leave in `ctx`: `& AuthAdds`… */
function addsOf(level: FnDecl | LoadDecl | RuleDecl, c: DeclCtx): string {
  return middlewaresOf(c, effective(c, level))
    .filter((m) => m.decl.adds !== undefined)
    .map((m) => ` & ${m.source === c.source ? '' : `import(${str(`fudic:${m.source.id}`)}).`}${pascal(m.decl.name.text)}Adds`)
    .join('');
}

const params = (c: DeclCtx): string => pageParams(c.api.route?.params ?? []);

function loadDecl(d: LoadDecl, c: DeclCtx): string {
  c.http.add('PageContext');
  c.http.add('PagePiece');
  c.http.add('BrowserLoadPiece');
  const lines = [
    `${I}export interface LoadData ${fieldsType(d.fields, c)}`,
    `${I}export type LoadCtx = PageContext<${params(c)}>${addsOf(d, c)};`,
    `${I}export type LoadHandler = (ctx: LoadCtx) => LoadData | Promise<LoadData>;`,
    // `fetch` is the browser module's: what the route's chunk asks the server with (SDD-68 §3.4).
    `${I}export const load: PagePiece<LoadHandler> & BrowserLoadPiece<LoadData>;`,
  ];
  return lines.join('\n');
}

function pathsDecl(_d: PathsDecl, c: DeclCtx): string {
  c.http.add('PagePiece');
  return `${I}export type PathsHandler = () => readonly string[] | Promise<readonly string[]>;\n${I}export const paths: PagePiece<PathsHandler>;`;
}

function layoutDecl(_d: LayoutDecl, c: DeclCtx): string {
  c.http.add('PageContext');
  c.http.add('PagePiece');
  const data = c.source.file.declarations.some((d) => d.kind === 'load') ? 'LoadData' : 'undefined';
  const props = c.api.route?.layoutProps ?? 'Readonly<Record<string, unknown>>';
  return `${I}export type LayoutHandler = (ctx: PageContext<${params(c)}>, data: ${data}) => ${props} | Promise<${props}>;\n${I}export const layout: PagePiece<LayoutHandler>;`;
}

/** The type of a form a function names, and its validated value. */
function formRef(d: FnDecl, c: DeclCtx): { readonly form: string; readonly value: string } | undefined {
  if (d.form === undefined) return undefined;
  const name = d.form.name.text;
  const form = projectRef(c, 'form', name, name);
  return form === undefined ? undefined : { form: `typeof ${form}`, value: projectRef(c, 'form', name, `${pascal(name)}Value`)! };
}

function fnDecl(d: FnDecl, c: DeclCtx): string {
  c.http.add('Contract');
  const prefix = pascal(d.name.text);
  const route = d.args.filter((a) => a.place === 'route');
  const query = d.args.filter((a) => a.place === 'query');
  const body = d.args.filter((a) => a.place === 'body');
  const page = c.api.route?.params ?? [];
  const pageFields = page.map((p) => `readonly ${p}: string`);
  const routeFields = fieldsType(route, c).slice(1, -1).trim();
  const p = [...pageFields, ...(routeFields === '' ? [] : [routeFields])];
  const P = p.length === 0 ? '{}' : `{ ${p.join('; ')} }`;
  const Q = fieldsType(query, c);
  const form = formRef(d, c);
  const R = d.returns === undefined ? 'void' : tsType(d.returns.type, c);

  let ctx: string;
  if (form !== undefined) {
    c.http.add('FormContext');
    c.forms.add('Validated');
    ctx = `FormContext<${P}, ${Q}, Validated<${form.form}, ${form.value}>>`;
  } else {
    c.http.add('FnContext');
    ctx = `FnContext<${P}, ${Q}, ${body.length === 0 ? 'undefined' : fieldsType(body, c)}>`;
  }
  const places = [...route, ...query];
  const call =
    form !== undefined
      ? places.length === 0
        ? form.form
        : `${fieldsType(places, c).slice(0, -2)}; readonly form: ${form.form} }`
      : places.length + body.length === 0
        ? 'void'
        : fieldsType([...places, ...body], c);

  // A `get` is a URL too, for a `href` or a `src` (SDD-81 §3.4).
  if (d.verb === 'get') c.http.add('Linkable');
  const linkable = d.verb === 'get' ? ` & Linkable<${call}>` : '';
  const lines = [
    `${I}export type ${prefix}Ctx = ${ctx}${addsOf(d, c)};`,
    `${I}export type ${prefix}Handler = (ctx: ${prefix}Ctx) => ${R} | Promise<${R}>;`,
    `${I}export const ${d.name.text}: Contract<${prefix}Ctx, ${R}, ${call}>${linkable};`,
  ];
  if (d.fails.length > 0) lines.push(`${I}export const ${prefix}Fails: ${failsType(d.fails, c)};`);
  return lines.join('\n');
}
