/**
 * `emitModule` (SDD-60 §3.11, §4.3): the virtual module `fudic:<id>` the Vite plugin serves, in
 * its server or its browser variant.
 *
 * Both export the same names. On the server a function is the contract `src/server` completes,
 * with its chain; in the browser it is the call, with its route, its query and the client halves
 * of its chain. What only the server implements fails in the browser with the folder it belongs
 * in. It imports `@fudic/*\/contract` and other `fudic:<id>`, never anything of the developer's.
 */

import type { CompressClause, Decl, FailsClause, FnDecl, LoadDecl, MiddlewareArg, MiddlewareDecl, RuleUse, SkipClause, UseClause } from '../ast.js';
import type { ApiIndex, ApiSource } from '../index-api.js';
import type { ApiContext } from '../validate.js';
import { isArgRule } from '../validate-form.js';
import { formCode } from './form.js';
import { canonical, fnv1a } from './signature.js';
import {
  borrowedForms,
  camel,
  clauses,
  descriptor,
  descriptors,
  effective,
  globalChain,
  hasChain,
  literal,
  pascal,
  projectRef,
  str,
  type EmitCtx,
} from './shared.js';

export type Side = 'server' | 'browser';

interface ModuleCtx extends EmitCtx {
  readonly api: ApiContext;
  readonly side: Side;
  readonly http: Set<string>;
  readonly forms: Set<string>;
  /** The names `@fudic/http/wire` must give. */
  readonly wire: Set<string>;
  /** The formats of this module's functions, and the reader of the data frames when it has `load`. */
  readonly wires: Set<'bin' | 'json' | 'frames'>;
  /** `fudic:<id>` → the names imported from it. */
  readonly imports: Map<string, Set<string>>;
}

/** Declarations in the order their values must exist. */
const ORDER: readonly Decl['kind'][] = ['type', 'enum', 'pattern', 'rule', 'middleware', 'messages', 'form', 'chain', 'load', 'paths', 'layout', 'fn'];

export function emitModule(source: ApiSource, index: ApiIndex, api: ApiContext, side: Side): string {
  const imports = new Map<string, Set<string>>();
  const c: ModuleCtx = {
    source,
    index,
    api,
    side,
    http: new Set(),
    forms: new Set(),
    wire: new Set(),
    wires: new Set(),
    imports,
    ref: (other, name) => {
      const names = imports.get(other.id) ?? new Set<string>();
      imports.set(other.id, names);
      names.add(name);
      return name;
    },
  };
  const decls = [...source.file.declarations].sort((a, b) => ORDER.indexOf(a.kind) - ORDER.indexOf(b.kind));
  const body = decls.map((d) => declaration(d, c)).filter((s) => s !== '');
  const borrowed = [...borrowedForms(c).values()].flat().sort();
  if (borrowed.length > 0) body.push(`export { ${borrowed.join(', ')} };`);

  const head: string[] = [];
  if (c.http.size > 0) head.push(`import { ${[...c.http].sort().join(', ')} } from '@fudic/http/contract';`);
  if (c.forms.size > 0) head.push(`import { ${[...c.forms].sort().join(', ')} } from '@fudic/forms/contract';`);
  if (c.wire.size > 0) head.push(`import { ${[...c.wire].sort().join(', ')} } from '@fudic/http/wire';`);
  // One format per module, as its functions need: a page bundles only the codecs it speaks.
  if (c.wires.has('bin')) head.push(`import { binWire } from '@fudic/http/wire/bin';`);
  if (c.wires.has('json')) head.push(`import { jsonWire } from '@fudic/http/wire/json';`);
  if (c.wires.has('frames')) head.push(`import { readFrames } from '@fudic/http/wire/frames';`);
  const messages = index.messages()[0];
  if (messages !== undefined && messages.source !== source && source.file.declarations.some((d) => d.kind === 'form')) {
    head.push(`import ${str(`fudic:${messages.source.id}`)};`);
  }
  for (const id of [...imports.keys()].sort()) {
    const names = [...imports.get(id)!].sort().map((n) => (n === '$chain' ? '$chain as $global' : n));
    head.push(`import { ${names.join(', ')} } from ${str(`fudic:${id}`)};`);
  }
  return `// Generated by fudic from ${source.id}.fudapi (${side}). Do not edit.\n${[...head, '', ...body].join('\n')}\n`;
}

function declaration(d: Decl, c: ModuleCtx): string {
  const id = str(c.source.id);
  switch (d.kind) {
    case 'type':
      return `export const $${d.name.text} = { fields: () => (${descriptors(d.fields, c)}) };`;
    case 'enum':
      return `export const $${d.name.text} = { oneOf: [${d.members.map((m) => str(m.text)).join(', ')}] };`;
    case 'pattern':
      return `export const ${camel(d.name.text)} = new RegExp(${str(`^(?:${d.source.text})$`)});`;
    case 'rule': {
      c.forms.add('rule');
      const fails = d.fails.map((f) => `[${str(f.code.text)}, [${f.params.map((p) => str(p.text)).join(', ')}]]`);
      const server = d.runs?.value.text === 'server';
      const flags = [...(server ? ['server: true'] : []), ...(d.async !== undefined ? ['async: true'] : []), ...(server && c.side === 'browser' ? ['never: true'] : [])];
      return `export const ${camel(d.name.text)} = rule({ id: ${id}, name: ${str(d.name.text)}, fails: [${fails.join(', ')}]${flags.map((f) => `, ${f}`).join('')} });`;
    }
    case 'middleware':
      return middleware(d, c);
    case 'messages':
      c.forms.add('messages');
      return `messages({ ${d.entries.map((e) => `${camel(e.code.text)}: ${str(e.text.text)}`).join(', ')} });`;
    case 'form':
      return `export const ${d.name.text} = ${formCode(d, c, c.forms)};`;
    case 'chain':
      return `export const $chain = ${level(d.uses, d.skips, d.compress, c)};`;
    case 'load':
      return load(d, c);
    case 'paths':
    case 'layout':
      c.http.add('page');
      return `export const ${d.kind} = page({ id: ${id}, name: ${str(d.kind)}${browser(c)} });`;
    case 'fn':
      return fn(d, c);
  }
}

const browser = (c: ModuleCtx): string => (c.side === 'browser' ? ', browser: true' : '');

function failsOf(name: string, fails: readonly FailsClause[], c: ModuleCtx): string {
  if (fails.length === 0) return '';
  c.http.add('fails');
  const entries = fails.map((f) => `${camel(f.code.text)}: [${f.status.value}${f.detail === undefined ? '' : `, ${str(f.detail.text)}`}]`);
  return `\nexport const ${name}Fails = fails({ ${entries.join(', ')} });`;
}

function middleware(d: MiddlewareDecl, c: ModuleCtx): string {
  c.http.add('middleware');
  const halves = [...(d.client !== undefined ? ['client: true'] : []), ...(d.server !== undefined ? ['server: true'] : [])];
  const head = `export const ${camel(d.name.text)} = middleware({ id: ${str(c.source.id)}, name: ${str(d.name.text)}${halves.map((h) => `, ${h}`).join('')}${browser(c)} });`;
  return head + failsOf(pascal(d.name.text), d.fails, c);
}

/** The parameters written under a `use`, as the object the middleware's halves receive. */
function params(args: readonly MiddlewareArg[], decl: MiddlewareDecl): string {
  const entries = decl.params.flatMap((p) => {
    const lines = args.filter((a) => a.name.text === p.name.text);
    if (lines.length === 0) return [];
    const type = p.type.kind === 'optional' ? p.type.inner : p.type;
    if (type.kind === 'map') {
      return [`${p.name.text}: { ${lines.map((l) => `${literal(l.values[0]!)}: ${literal(l.values[1]!)}`).join(', ')} }`];
    }
    const values = lines[0]!.values;
    if (type.kind === 'list') {
      const items = values.filter((v) => v.kind !== 'empty-list');
      return [`${p.name.text}: [${items.map(literal).join(', ')}]`];
    }
    return [`${p.name.text}: ${literal(values[0]!)}`];
  });
  return `{ ${entries.join(', ')} }`;
}

/** One level of a chain: its clauses in order, and its `compress`. */
function level(uses: readonly UseClause[], skips: readonly SkipClause[], compress: CompressClause | undefined, c: ModuleCtx): string {
  const mw = (name: string): string | undefined => projectRef(c, 'middleware', name);
  const steps = clauses(uses, skips).map((clause) => {
    if (clause.kind === 'skip') {
      if (clause.all !== undefined) return `{ skip: '*' }`;
      return `{ skip: [${clause.middlewares.flatMap((n) => mw(n.text) ?? []).join(', ')}] }`;
    }
    c.http.add('use');
    const refs = clause.middlewares.flatMap((m) => {
      const ref = mw(m.name.text);
      if (ref === undefined) return [];
      const decl = c.index.lookup('middleware', m.name.text)!.decl;
      return [m.args.length === 0 ? `use(${ref})` : `use(${ref}, ${params(m.args, decl)})`];
    });
    return `{ use: [${refs.join(', ')}] }`;
  });
  const parts = [`steps: [${steps.join(', ')}]`];
  if (compress !== undefined) {
    if (compress.off !== undefined) parts.push('compress: false');
    else parts.push(`compress: { format: ${str(compress.encoding!.text)}${compress.min === undefined ? '' : `, min: ${compress.min.value}`} }`);
  }
  return `{ ${parts.join(', ')} }`;
}

/** The levels around a function or `load`: global, file, its own. */
function chainOf(own: string, c: ModuleCtx): string {
  const global = globalChain(c);
  if (global !== undefined) c.ref(global, '$chain');
  const outer = [...(global !== undefined ? ['$global'] : []), ...(hasChain(c.source.file.declarations) ? ['$chain'] : [])];
  return `[${[...outer, own].join(', ')}]`;
}

function load(d: LoadDecl, c: ModuleCtx): string {
  c.http.add('page');
  const chain = chainOf(level(d.uses, d.skips, undefined, c), c);
  // The fields that arrive later (SDD-70): `runLoad` settles each one as soon as `load` returns.
  const later = d.fields.filter((f) => f.later !== undefined).map((f) => str(f.name.text));
  const settles = later.length === 0 ? '' : `, later: [${later.join(', ')}]`;
  // The type of every field, a `later` one by what it resolves to: what the data endpoint writes
  // its frames with, and what the browser reads them back with (SDD-70 §3.7).
  const fields = d.fields.length === 0 ? '' : `, fields: ${descriptors(d.fields, c)}`;
  c.wires.add('frames');
  return `export const load = page({ id: ${str(c.source.id)}, name: "load", chain: ${chain}${fields}${settles}, read: readFrames${browser(c)} });${failsOf('Load', d.fails, c)}`;
}

/** The validators of `@fudic/forms/contract` by rule, imported under `$` so no rule shadows them. */
const VALIDATORS: Readonly<Record<string, string>> = {
  required: 'required',
  min: 'min',
  max: 'max',
  'min-length': 'minLength',
  'max-length': 'maxLength',
  pattern: 'pattern',
};

/** One rule under an argument (SDD-67 §3.5): its validator built with its arguments, as written. */
function argRule(use: RuleUse, c: ModuleCtx): string | undefined {
  const found = c.index.lookup('rule', use.name.text);
  if (found === undefined || !isArgRule(found)) return undefined;
  const name = VALIDATORS[use.name.text]!;
  c.forms.add(`${name} as $${name}`);
  // `pattern` names a pattern of the project, as in a form: its RegExp is what the validator takes.
  const values = use.args.map((a) => (a.kind === 'word' ? (projectRef(c, 'pattern', a.text) ?? 'undefined') : literal(a)));
  const check = name === 'required' ? '$required' : `$${name}(${values.join(', ')})`;
  const text = use.text === undefined ? '' : `, text: ${str(use.text.text)}`;
  return `{ check: ${check}, name: ${str(use.name.text)}, args: [${use.args.map(literal).join(', ')}]${text} }`;
}

/** The rules of a function's arguments, by argument in declaration order; `undefined` with none. */
function argRules(d: FnDecl, c: ModuleCtx): string | undefined {
  const entries = d.args.flatMap((a) => {
    const rules = a.rules.flatMap((r) => argRule(r, c) ?? []);
    return rules.length === 0 ? [] : [`${a.name.text}: [${rules.join(', ')}]`];
  });
  return entries.length === 0 ? undefined : `{ ${entries.join(', ')} }`;
}

function fn(d: FnDecl, c: ModuleCtx): string {
  const kind = c.side === 'server' ? 'fn' : 'stub';
  c.http.add(kind);
  const typed = (place: string): string | undefined => {
    const args = d.args.filter((a) => a.place === place);
    return args.length === 0 ? undefined : descriptors(args, c);
  };
  const form = d.form === undefined ? undefined : projectRef(c, 'form', d.form.name.text, d.form.name.text);
  if (form !== undefined) c.wire.add('formTypes');
  // A form's controls are its body (SDD-67 §3.1): the call writes them and the server reads them.
  const body = form === undefined ? typed('body') : `formTypes(${form}.$schema)`;
  // `json` left in the chain once its three levels are folded: the function speaks JSON (§3.4).
  const json = effective(c, d).includes('json');
  c.wires.add(json ? 'json' : 'bin');
  const rules = argRules(d, c);
  const fields = [
    `id: ${str(c.source.id)}`,
    `name: ${str(d.name.text)}`,
    `method: ${str(d.verb.toUpperCase())}`,
    ...(c.api.route?.pattern !== undefined ? [`page: ${str(c.api.route.pattern)}`] : []),
    ...(d.route !== undefined ? [`route: [${d.route.segments.map((s) => str(s.kind === 'param' ? `:${s.text}` : s.text)).join(', ')}]`] : []),
    ...(typed('route') !== undefined ? [`params: ${typed('route')}`] : []),
    ...(typed('query') !== undefined ? [`query: ${typed('query')}`] : []),
    ...(body !== undefined ? [`args: ${body}`] : []),
    ...(form !== undefined ? [`form: ${form}`] : []),
    `wire: ${json ? 'jsonWire' : 'binWire'}`,
    ...(json ? [] : [`sig: ${str(fnv1a(canonical(d, c.index)))}`]),
    ...(d.returns !== undefined ? [`returns: ${descriptor(d.returns.type, c)}`] : []),
    ...(rules !== undefined ? [`rules: ${rules}`] : []),
    `chain: ${chainOf(level(d.uses, d.skips, d.compress, c), c)}`,
    ...(d.invalidates.length > 0 ? [`invalidates: [${d.invalidates.flatMap((i) => i.routes).map((r) => str(r.text)).join(', ')}]`] : []),
  ];
  return `export const ${d.name.text} = ${kind}({ ${fields.join(', ')} });${failsOf(pascal(d.name.text), d.fails, c)}`;
}
