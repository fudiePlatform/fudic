/**
 * `planShowcase` and `executeFixtures` (SDD-66 §3.2, §4.2) — criteria 7–10 and the determinism
 * of §4.2, over the pure plan; the fixtures executed as the workbench executes them.
 *
 * Criterion 12 (the workbench's pages do not change) is `pages.test.ts` and `host.test.ts`,
 * untouched: they compare against `test/expected/`, which this phase did not edit.
 */

import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  executeFixtures,
  isShowcaseFile,
  planShowcase,
  showcaseMark,
  type ExecutedFixtures,
  type ShowcaseComponent,
  type ShowcaseInput,
} from '../src/index.js';

/** A signal as the fixture holds it, without pulling in the runtime. */
function signal<T>(value: T): (() => T) & { set(next: T): void } {
  let current = value;
  return Object.assign(() => current, { set: (next: T) => void (current = next) });
}

const COMMAND = 'fudic g showcase ui';
const MARK = showcaseMark(COMMAND);
const ROUTES = 'apps/showcase/src/routes';
const HOSTS = 'apps/showcase/src/components/showcase';

function component(tag: string, cases: ExecutedFixtures): ShowcaseComponent {
  return {
    tag,
    href: `@acme/ui/${tag}.fud`,
    fixture: `@acme/ui/${tag}.fixture`,
    fromHosts: { href: `@acme/ui/${tag}.fud`, fixture: `@acme/ui/${tag}.fixture` },
    cases,
    file: `libs/ui/src/components/${tag}/${tag}.fixture.ts`,
  };
}

const BUTTON = component('acme-button', {
  primary: { variant: 'primary', $content: 'Save' },
  disabled: { variant: 'primary', disabled: true, $content: 'Save' },
});

function input(overrides: Partial<ShowcaseInput> = {}): ShowcaseInput {
  return {
    command: COMMAND,
    components: [BUTTON],
    routesDir: ROUTES,
    hostsDir: HOSTS,
    hostsHref: '../components/showcase',
    layout: '../layouts/_layout.fud',
    lang: 'en',
    url: '/showcase/',
    source: 'libs/ui',
    existing: new Map(),
    ...overrides,
  };
}

/** The contents the plan writes, by path. */
function written(plan: ReturnType<typeof planShowcase>): ReadonlyMap<string, string> {
  return new Map(plan.changes.map((change) => [change.path, change.contents]));
}

describe('the page of a component (§3.2)', () => {
  it('one block per case, in fixture order; each prop read into <case><Prop> and $content as children', () => {
    const plan = planShowcase(input());
    expect(plan.errors).toEqual([]);
    expect(plan.diagnostics).toEqual([]);
    expect(plan.deletions).toEqual([]);
    expect(written(plan).get(`${ROUTES}/acme-button.fud`)).toBe(`${MARK}
<link rel="layout" href="../layouts/_layout.fud">
<link rel="component" href="@acme/ui/acme-button.fud">

@code {
  import cases from '@acme/ui/acme-button.fixture';

  const { variant: primaryVariant } = cases.primary;
  const { variant: disabledVariant, disabled: disabledDisabled } = cases.disabled;
}

<head>
  <title>acme-button</title>
</head>

<h1>acme-button</h1>

<section>
  <h2>primary</h2>
  <acme-button .variant=@primaryVariant>Save</acme-button>
</section>

<section>
  <h2>disabled</h2>
  <acme-button .variant=@disabledVariant .disabled=@disabledDisabled>Save</acme-button>
</section>
`);
  });

  it('the mark is the first line of every file with a layout, and names the command to run again', () => {
    expect(MARK).toBe('<!-- Generated by `fudic g showcase ui`. Run it again instead of editing this file. -->');
    for (const contents of written(planShowcase(input())).values()) {
      expect(contents.split('\n')[0]).toBe(MARK);
      expect(isShowcaseFile(contents)).toBe(true);
    }
    expect(isShowcaseFile('<h1>mine</h1>\n')).toBe(false);
    expect(isShowcaseFile('<!-- Generated by `fudic g page`. -->\n')).toBe(false);
    // A whole document carries it after its DOCTYPE, and is the showcase's all the same.
    expect(isShowcaseFile(`<!DOCTYPE html>\n${MARK}\n<html lang="en"></html>\n`)).toBe(true);
    expect(isShowcaseFile('<!DOCTYPE html>\n<html lang="en"></html>\n')).toBe(false);
  });

  it('a case with no props mounts the bare component, and a component with only those has no @code', () => {
    const plan = planShowcase(input({ components: [component('acme-icon', { solo: {} })] }));
    const page = written(plan).get(`${ROUTES}/acme-icon.fud`)!;
    expect(page).toContain('<acme-icon></acme-icon>');
    // Nothing to read: the case has no props, so the page has no @code.
    expect(page).not.toContain('@code');
  });

  it('the index links each page, with the tag as its text, in the order given', () => {
    const plan = planShowcase(input({ components: [BUTTON, component('acme-card', { base: { title: 'T' } })] }));
    expect(written(plan).get(`${ROUTES}/index.fud`)).toBe(`${MARK}
<link rel="layout" href="../layouts/_layout.fud">

<head>
  <title>Showcase</title>
</head>

<h1>Showcase</h1>

<ul>
  <li><a href="/showcase/acme-button">acme-button</a></li>
  <li><a href="/showcase/acme-card">acme-card</a></li>
</ul>
`);
  });

  it('without a layout, each page is a whole document with its links in <head>', () => {
    const plan = planShowcase(input({ layout: null, lang: 'es' }));
    // The mark goes after the DOCTYPE: a comment before it would not leave a page a page.
    expect(written(plan).get(`${ROUTES}/acme-button.fud`)).toBe(`<!DOCTYPE html>
${MARK}
<html lang="es">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <link rel="component" href="@acme/ui/acme-button.fud">
    @code {
      import cases from '@acme/ui/acme-button.fixture';

      const { variant: primaryVariant } = cases.primary;
      const { variant: disabledVariant, disabled: disabledDisabled } = cases.disabled;
    }
    <script type="module" src="fudic:runtime"></script>
    <title>acme-button</title>
  </head>
  <body>
    <h1>acme-button</h1>

    <section>
      <h2>primary</h2>
      <acme-button .variant=@primaryVariant>Save</acme-button>
    </section>

    <section>
      <h2>disabled</h2>
      <acme-button .variant=@disabledVariant .disabled=@disabledDisabled>Save</acme-button>
    </section>
  </body>
</html>
`);
    const index = written(plan).get(`${ROUTES}/index.fud`)!;
    expect(index).toContain('<html lang="es">');
    expect(index).not.toContain('@code');
    expect(index).not.toContain('rel="component"');
  });

  it('is deterministic: the same input gives the same files, byte for byte', () => {
    expect(planShowcase(input())).toEqual(planShowcase(input()));
  });
});

describe('criterion 7: one variable per case', () => {
  it("'titulo-largo' reads into tituloLargo<Prop>; a clash is numbered, and `cases` is taken", () => {
    const plan = planShowcase(
      input({
        components: [
          component('acme-card', {
            'titulo-largo': { title: 'a' },
            tituloLargo: { title: 'b' },
            'titulo largo': { title: 'c' },
            cases: { title: 'd' },
            '2-col': { title: 'e' },
            'Con-Mayúscula': { title: 'f' },
          }),
        ],
      }),
    );
    const page = written(plan).get(`${ROUTES}/acme-card.fud`)!;
    // A name that is an identifier is read with a dot; any other, with brackets.
    expect(page).toContain(`  const { title: tituloLargoTitle } = cases["titulo-largo"];
  const { title: tituloLargo2Title } = cases.tituloLargo;
  const { title: tituloLargo3Title } = cases["titulo largo"];
  const { title: cases2Title } = cases.cases;
  const { title: case2ColTitle } = cases["2-col"];
  const { title: conMaySculaTitle } = cases["Con-Mayúscula"];`);
    // The heading keeps the case's own name; the constant is only how the view reads it.
    expect(page).toContain('<h2>titulo-largo</h2>\n  <acme-card .title=@tituloLargoTitle></acme-card>');
    expect(page).toContain('<h2>cases</h2>\n  <acme-card .title=@cases2Title></acme-card>');
  });

  it('a constant that clashes with a case or with another constant is numbered', () => {
    const plan = planShowcase(
      input({
        components: [
          component('acme-button', {
            primary: { variant: 'a' },
            primaryVariant: { x: 'b' },
            a: { bC: 'c' },
            aB: { c: 'd' },
          }),
        ],
      }),
    );
    const page = written(plan).get(`${ROUTES}/acme-button.fud`)!;
    expect(page).toContain(`  const { variant: primaryVariant2 } = cases.primary;
  const { x: primaryVariantX } = cases.primaryVariant;
  const { bC: aBC } = cases.a;
  const { c: aBC2 } = cases.aB;`);
    expect(page).toContain('<acme-button .variant=@primaryVariant2></acme-button>');
    expect(page).toContain('<acme-button .c=@aBC2></acme-button>');
  });

  it('a case with a signal prop is mounted through a host in the hosts folder, which the page links', () => {
    const counter = component('acme-counter', {
      'cuenta-larga': { value: signal(10), label: 'Clicks', $content: 'more' },
      fijo: { label: 'Fixed' },
    });
    const plan = planShowcase(input({ components: [counter] }));
    expect(plan.errors).toEqual([]);
    const files = written(plan);
    const host = files.get(`${HOSTS}/showcase-acme-counter-cuenta-larga.fud`)!;
    expect(host).toBe(`${MARK}
<link rel="component" href="@acme/ui/acme-counter.fud">

@code {
  import { signal } from "@fudic/core";
  import fixtures from "@acme/ui/acme-counter.fixture";

  const { label } = fixtures["cuenta-larga"];

  const value = signal(10);
}

<showcase-acme-counter-cuenta-larga>
  <template shadowrootmode="open">
    <acme-counter .value=@value .label=@label>more</acme-counter>
  </template>
</showcase-acme-counter-cuenta-larga>
`);
    const page = files.get(`${ROUTES}/acme-counter.fud`)!;
    expect(page).toContain(
      '<link rel="component" href="@acme/ui/acme-counter.fud">\n<link rel="component" href="../components/showcase/showcase-acme-counter-cuenta-larga.fud">',
    );
    expect(page).toContain('<h2>cuenta-larga</h2>\n  <showcase-acme-counter-cuenta-larga></showcase-acme-counter-cuenta-larga>');
    // The page reads only the cases it mounts itself.
    expect(page).toContain('  const { label: fijoLabel } = cases.fijo;\n}');
    expect(page).toContain('<acme-counter .label=@fijoLabel></acme-counter>');
    expect(page).not.toContain('cases["cuenta-larga"]');
  });

  it('a page whose every case has a signal has no @code of its own', () => {
    const plan = planShowcase(input({ components: [component('acme-counter', { uno: { value: signal(1) } })] }));
    const page = written(plan).get(`${ROUTES}/acme-counter.fud`)!;
    expect(page).not.toContain('@code');
    expect(written(plan).get(`${HOSTS}/showcase-acme-counter-uno.fud`)).toContain('const value = signal(1);');
  });

  it('a signal whose value is not a JSON literal is FUD0974, and its block is left out', () => {
    const plan = planShowcase(
      input({
        components: [component('acme-counter', { roto: { value: signal(new Date(0)) }, bien: { value: signal(2) } })],
      }),
    );
    expect(plan.diagnostics.map((d) => d.code)).toEqual(['FUD0974']);
    expect(plan.diagnostics[0]!.message).toContain('value');
    const files = written(plan);
    expect(files.get(`${ROUTES}/acme-counter.fud`)).not.toContain('<h2>roto</h2>');
    expect(files.has(`${HOSTS}/showcase-acme-counter-roto.fud`)).toBe(false);
    expect(files.has(`${HOSTS}/showcase-acme-counter-bien.fud`)).toBe(true);
  });
});

describe('criterion 8: run it again', () => {
  const first = planShowcase(input());
  const existing = new Map(first.changes.map((change) => [change.path, change.contents]));

  it('with nothing changed, writes nothing and deletes nothing', () => {
    const again = planShowcase(input({ existing }));
    expect(again).toEqual({ changes: [], deletions: [], errors: [], diagnostics: [] });
  });

  it('a new case rewrites only that page, without --force', () => {
    const grown = component('acme-button', { ...BUTTON.cases, ghost: { variant: 'ghost', $content: 'Save' } });
    const again = planShowcase(input({ components: [grown], existing }));
    expect(again.errors).toEqual([]);
    expect(again.changes.map((change) => [change.kind, change.path])).toEqual([['modify', `${ROUTES}/acme-button.fud`]]);
    const change = again.changes[0]!;
    expect(change.kind === 'modify' && change.before).toBe(existing.get(`${ROUTES}/acme-button.fud`));
    expect(change.contents).toContain('<h2>ghost</h2>');
  });

  it('a new component adds its page and its line in the index', () => {
    const again = planShowcase(input({ components: [BUTTON, component('acme-card', { base: { title: 'T' } })], existing }));
    expect(again.changes.map((change) => [change.kind, change.path])).toEqual([
      ['create', `${ROUTES}/acme-card.fud`],
      ['modify', `${ROUTES}/index.fud`],
    ]);
  });

  it('a component that lost its fixture loses its page and its hosts', () => {
    const counter = component('acme-counter', { uno: { value: signal(1) } });
    const both = planShowcase(input({ components: [BUTTON, counter] }));
    const there = new Map(both.changes.map((change) => [change.path, change.contents]));
    // Somebody's own file in the hosts folder is never the showcase's to delete.
    there.set(`${HOSTS}/mine.fud`, '<h1>mine</h1>\n');

    const again = planShowcase(input({ components: [BUTTON, component('acme-counter', {})], existing: there }));
    expect(again.errors).toEqual([]);
    expect([...again.deletions].sort()).toEqual([`${HOSTS}/showcase-acme-counter-uno.fud`, `${ROUTES}/acme-counter.fud`]);
    expect(again.changes.map((change) => change.path)).toEqual([`${ROUTES}/index.fud`]);
  });
});

describe('criterion 9: a file without the mark', () => {
  it('in the place of a page is FUD0443, and nothing is written or deleted', () => {
    const existing = new Map([
      [`${ROUTES}/acme-button.fud`, '<h1>my own page</h1>\n'],
      [`${ROUTES}/old.fud`, `${MARK}\n<h1>old</h1>\n`],
    ]);
    const plan = planShowcase(input({ existing }));
    expect(plan.errors.map((e) => e.code)).toEqual(['FUD0443']);
    expect(plan.errors[0]!.message).toContain(`${ROUTES}/acme-button.fud`);
    expect(plan.changes).toEqual([]);
    expect(plan.deletions).toEqual([]);
  });

  it('in the place of the index, or of a host, too', () => {
    const counter = component('acme-counter', { uno: { value: signal(1) } });
    const existing = new Map([
      [`${ROUTES}/index.fud`, '<h1>home</h1>\n'],
      [`${HOSTS}/showcase-acme-counter-uno.fud`, '<x-y></x-y>\n'],
    ]);
    const plan = planShowcase(input({ components: [counter], existing }));
    expect(plan.errors.map((e) => e.code)).toEqual(['FUD0443', 'FUD0443']);
    expect(plan.changes).toEqual([]);
  });
});

describe('criterion 10: nothing to show', () => {
  it('no component, or none with a case, is FUD1242 on the source', () => {
    for (const components of [[], [component('acme-empty', {})]]) {
      const plan = planShowcase(input({ components }));
      expect(plan.errors.map((e) => e.code)).toEqual(['FUD1242']);
      expect(plan.errors[0]!.message).toContain('libs/ui');
      expect(plan.changes).toEqual([]);
      expect(plan.deletions).toEqual([]);
    }
  });
});

describe('executeFixtures', () => {
  it('runs each fixture through Vite, signals included', async () => {
    const root = fileURLToPath(new URL('./fixtures/project/', import.meta.url));
    const file = join(root, 'src/components/app-bump.fixture.ts');
    const { fixtures, diagnostics } = await executeFixtures(root, [file]);
    expect(diagnostics).toEqual([]);
    const value = fixtures.get(file)!['diez']!['value'] as () => number;
    expect(typeof value).toBe('function');
    expect(value()).toBe(10);
  }, 60_000);

  it('a fixture that throws is FUD0973 and left out; one with no default export is empty', async () => {
    const root = mkdtempSync(join(tmpdir(), 'fudic-showcase-fixtures-'));
    const good = join(root, 'good.fixture.ts');
    const bad = join(root, 'bad.fixture.ts');
    const none = join(root, 'none.fixture.ts');
    writeFileSync(good, "export default { base: { title: 'T' } };\n");
    writeFileSync(bad, "throw new Error('broken fixture');\n");
    writeFileSync(none, 'export const x = 1;\n');
    const { fixtures, diagnostics } = await executeFixtures(root, [good, bad, none]);
    expect(fixtures.get(good)).toEqual({ base: { title: 'T' } });
    expect(fixtures.get(none)).toEqual({});
    expect(fixtures.has(bad)).toBe(false);
    expect(diagnostics.map((d) => d.code)).toEqual(['FUD0973']);
    expect(diagnostics[0]!.message).toContain('broken fixture');
  }, 60_000);
});
