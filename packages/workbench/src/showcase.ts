/**
 * `planShowcase` (SDD-66 §3.2, §4.2): a page per component with a block per case of its fixture,
 * the hosts of the cases with signals, and an index. Pure: it takes the EXECUTED fixtures and the
 * files already there, and answers what to write and what to delete; the CLI applies it.
 *
 * Everything it writes carries a mark on its first line. The mark is what makes it regenerable:
 * a marked file is the showcase's and is rewritten without `--force`; one without it is
 * somebody's, and is `FUD0443`.
 */

import { FUD0443, FUD0974, FUD1242, type FudDiagnostic } from '@fudic/diagnostics';
import { fixtureOf } from './access.js';
import { hostComponent } from './host.js';
import { caseShape, propAttrs, signalLiterals } from './mount-source.js';
import type { ExecutedFixtures } from './pages.js';

/** The start of the first line of every file the showcase writes. */
const MARK_START = '<!-- Generated by `';

/** The mark of a file `command` wrote. */
export function showcaseMark(command: string): string {
  return `${MARK_START}${command}\`. Run it again instead of editing this file. -->`;
}

/**
 * Whether a file is the showcase's: its first line is the mark of a `fudic g showcase` — its
 * second in a whole document, where nothing may come before the `<!DOCTYPE html>`.
 */
export function isShowcaseFile(contents: string): boolean {
  return contents.replace(/^<!DOCTYPE html>\n/u, '').startsWith(`${MARK_START}fudic g showcase`);
}

/** A component to show: how a page links it and imports its cases, and the cases, executed. */
export interface ShowcaseComponent {
  readonly tag: string;
  /** The `href` of its `<link rel="component">` from a page of the showcase. */
  readonly href: string;
  /** The specifier a page imports its fixture with. */
  readonly fixture: string;
  readonly cases: ExecutedFixtures;
  /** The same two, from the hosts' folder: a host links the component and imports its cases too. */
  readonly fromHosts: { readonly href: string; readonly fixture: string };
  /** Its fixture's file, for the diagnostics. */
  readonly file: string;
}

export interface ShowcaseInput {
  /** The command as typed, `fudic g showcase ui`: what the mark says to run again. */
  readonly command: string;
  /** In order: the pages and the index follow it. */
  readonly components: readonly ShowcaseComponent[];
  /** Where the pages go, relative to the working directory. */
  readonly routesDir: string;
  /** Where the hosts go, relative to the working directory. */
  readonly hostsDir: string;
  /** The `href` of the hosts' folder from a page. */
  readonly hostsHref: string;
  /** The `href` of the layout from a page, or `null` when the pages are whole documents. */
  readonly layout: string | null;
  /** With no layout, the language of the document. */
  readonly lang: string;
  /** The URL of the folder of the pages, ending in `/`: what the index links. */
  readonly url: string;
  /** What `FUD1242` names when there is nothing to show. */
  readonly source: string;
  /** Every file in `routesDir` and `hostsDir` now, by path, with its contents. */
  readonly existing: ReadonlyMap<string, string>;
}

export type ShowcaseChange =
  | { readonly kind: 'create'; readonly path: string; readonly contents: string }
  | { readonly kind: 'modify'; readonly path: string; readonly contents: string; readonly before: string };

export interface ShowcasePlan {
  readonly changes: readonly ShowcaseChange[];
  /** Marked files of a component that no longer has cases. */
  readonly deletions: readonly string[];
  /** `FUD0443` (a file without the mark in the way) and `FUD1242`: nothing is written. */
  readonly errors: readonly FudDiagnostic[];
  /** `FUD0974`: a case whose signal cannot be written down; its block is left out. */
  readonly diagnostics: readonly FudDiagnostic[];
}

export function planShowcase(input: ShowcaseInput): ShowcasePlan {
  const shown = input.components.filter((component) => Object.keys(component.cases).length > 0);
  if (shown.length === 0) return { changes: [], deletions: [], errors: [FUD1242({ file: input.source })], diagnostics: [] };

  const mark = showcaseMark(input.command);
  const files = new Map<string, string>();
  const diagnostics: FudDiagnostic[] = [];
  for (const component of shown) {
    const page = pageOf(component, input, mark, files, diagnostics);
    files.set(`${input.routesDir}/${component.tag}.fud`, page);
  }
  files.set(`${input.routesDir}/index.fud`, indexOf(shown, input, mark));

  const changes: ShowcaseChange[] = [];
  const errors: FudDiagnostic[] = [];
  for (const [path, contents] of files) {
    const before = input.existing.get(path);
    if (before === undefined) changes.push({ kind: 'create', path, contents });
    else if (!isShowcaseFile(before)) errors.push(FUD0443({ file: path, target: 'file' }));
    else if (before !== contents) changes.push({ kind: 'modify', path, contents, before });
  }
  const deletions = [...input.existing]
    .filter(([path, contents]) => !files.has(path) && isShowcaseFile(contents))
    .map(([path]) => path);
  return errors.length > 0 ? { changes: [], deletions: [], errors, diagnostics } : { changes, deletions, errors, diagnostics };
}

/** The variable a case is read into: its name if it is one, else camelCase, numbered on a clash. */
function variables(cases: readonly string[]): readonly string[] {
  const taken = new Set(['cases']);
  return cases.map((name) => {
    const base = identifier(name);
    let candidate = base;
    for (let n = 2; taken.has(candidate); n += 1) candidate = `${base}${n}`;
    taken.add(candidate);
    return candidate;
  });
}

/** `titulo-largo` → `tituloLargo`; one that does not start with a letter gets `case` in front. */
function identifier(name: string): string {
  if (/^[A-Za-z_$][\w$]*$/u.test(name)) return name;
  const words = name.split(/[^A-Za-z0-9]+/u).filter((word) => word !== '');
  const camel = words.map((word, i) => (i === 0 ? word.charAt(0).toLowerCase() + word.slice(1) : word.charAt(0).toUpperCase() + word.slice(1))).join('');
  return /^[A-Za-z]/u.test(camel) ? camel : `case${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
}

/** A name for a file and a tag: `titulo-largo`, `Primary 2` → `primary-2`. */
function kebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/gu, '$1-$2').toLowerCase().split(/[^a-z0-9]+/u).filter((word) => word !== '').join('-');
}

function pageOf(component: ShowcaseComponent, input: ShowcaseInput, mark: string, files: Map<string, string>, diagnostics: FudDiagnostic[]): string {
  const names = Object.keys(component.cases);
  const vars = variables(names);
  const links = [`<link rel="component" href="${component.href}">`];
  const reads: string[] = [];
  const blocks: string[] = [];

  // One const per prop, as the workbench reads them: a case's object has no type the portable view
  // ports (FUD1153), each of its props does. `primary` + `variant` → `primaryVariant`.
  const taken = new Set(['cases', ...vars]);
  const local = (variable: string, prop: string): string => {
    const base = `${variable}${prop.charAt(0).toUpperCase()}${prop.slice(1)}`;
    let candidate = base;
    for (let n = 2; taken.has(candidate); n += 1) candidate = `${base}${n}`;
    taken.add(candidate);
    return candidate;
  };

  names.forEach((name, i) => {
    const shape = caseShape(component.cases[name]!);
    const variable = vars[i]!;
    if (shape.signals.length === 0) {
      const locals = new Map(shape.order.map((prop) => [prop, local(variable, prop)]));
      if (locals.size > 0) reads.push(`  const { ${[...locals].map(([prop, name]) => `${prop}: ${name}`).join(', ')} } = ${fixtureOf(name, 'cases')};`);
      const attrs = propAttrs(shape.order, (prop) => locals.get(prop)!);
      blocks.push(block(name, `<${component.tag}${attrs}>${shape.content}</${component.tag}>`));
      return;
    }
    const seeded = signalLiterals(shape);
    if ('failed' in seeded) {
      diagnostics.push(FUD0974({ file: component.file, fixture: name, prop: seeded.failed }));
      return;
    }
    const hostTag = `showcase-${component.tag}-${kebab(variable)}`;
    files.set(
      `${input.hostsDir}/${hostTag}.fud`,
      `${mark}\n${hostComponent({
        tag: hostTag,
        component: component.fromHosts.href,
        componentTag: component.tag,
        fixture: { specifier: component.fromHosts.fixture, name },
        signals: seeded.literals,
        forwarded: shape.order.filter((prop) => !shape.signals.includes(prop)),
        order: shape.order,
        content: shape.content,
      })}`,
    );
    links.push(`<link rel="component" href="${input.hostsHref}/${hostTag}.fud">`);
    blocks.push(block(name, `<${hostTag}></${hostTag}>`));
  });

  const code = reads.length === 0 ? '' : `@code {\n  import cases from '${component.fixture}';\n\n${reads.join('\n')}\n}\n\n`;
  return documentOf(input, mark, component.tag, links, code, `<h1>${component.tag}</h1>\n\n${blocks.join('\n\n')}\n`);
}

function block(name: string, mount: string): string {
  return `<section>\n  <h2>${name}</h2>\n  ${mount}\n</section>`;
}

function indexOf(shown: readonly ShowcaseComponent[], input: ShowcaseInput, mark: string): string {
  const items = shown.map((component) => `  <li><a href="${input.url}${component.tag}">${component.tag}</a></li>`).join('\n');
  return documentOf(input, mark, 'Showcase', [], '', `<h1>Showcase</h1>\n\n<ul>\n${items}\n</ul>\n`);
}

/** A route inside the layout, as `g page` writes it, or a whole document when there is none. */
function documentOf(input: ShowcaseInput, mark: string, title: string, links: readonly string[], code: string, body: string): string {
  if (input.layout !== null) {
    const head = [`<link rel="layout" href="${input.layout}">`, ...links].join('\n');
    return `${mark}\n${head}\n\n${code}<head>\n  <title>${title}</title>\n</head>\n\n${body}`;
  }
  const inHead = links.map((link) => `    ${link}\n`).join('');
  const inCode = code === '' ? '' : `${code.trimEnd().split('\n').map((line) => (line === '' ? line : `    ${line}`)).join('\n')}\n`;
  const indented = body.trimEnd().split('\n').map((line) => (line === '' ? line : `    ${line}`)).join('\n');
  return (
    `<!DOCTYPE html>\n${mark}\n<html lang="${input.lang}">\n  <head>\n    <meta charset="utf-8">\n` +
    `    <meta name="viewport" content="width=device-width, initial-scale=1">\n${inHead}${inCode}` +
    `    <script type="module" src="fudic:runtime"></script>\n    <title>${title}</title>\n  </head>\n  <body>\n${indented}\n  </body>\n</html>\n`
  );
}
