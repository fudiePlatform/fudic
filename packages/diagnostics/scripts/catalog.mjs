// Writes `src/catalog.generated.ts` from the `.md` beside every code: its title and severity, or,
// for a retired one, the codes that replaced it. Run it after adding or retiring a code:
//
//   pnpm --filter @fudic/diagnostics catalog
//
// A test compares the generated table with the folder, so a code added without running this fails.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const CODES = new URL('../src/codes/', import.meta.url);
const OUT = new URL('../src/catalog.generated.ts', import.meta.url);

const live = [];
const retired = [];
for (const name of readdirSync(CODES).filter((f) => /^FUD\d{4}\.md$/u.test(f)).sort()) {
  const code = name.slice(0, -3);
  const lines = readFileSync(new URL(name, CODES), 'utf8').replace(/\r\n/gu, '\n').trimEnd().split('\n');
  const title = lines[0].replace(/^# FUD\d{4} — /u, '');
  const status = /^\*\*(\w+)\*\*$/u.exec(lines[1])[1];
  if (status === 'retired') {
    const by = [...(lines.at(-1).match(/FUD\d{4}/gu) ?? [])];
    retired.push(`  ${code}: [${JSON.stringify(title)}, [${by.map((c) => `'${c}'`).join(', ')}]],`);
  } else {
    live.push(`  ${code}: ['${status}', ${JSON.stringify(title)}],`);
  }
}

writeFileSync(
  OUT,
  `// Generated by scripts/catalog.mjs from src/codes/*.md: do not edit by hand.

import type { FudCode, Severity } from './types.js';

/** Every live code: its severity and its title. */
export const LIVE: Readonly<Record<string, readonly [Severity, string]>> = {
${live.join('\n')}
};

/** Every retired code: its title and the codes that replaced it. */
export const RETIRED: Readonly<Record<string, readonly [string, readonly FudCode[]]>> = {
${retired.join('\n')}
};
`,
);
