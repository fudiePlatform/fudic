/**
 * The generated root (SDD-60 §4.4): the module that loads the implementations a developer
 * wrote in `src/server` and `src/browser`, and those a library publishes in its `server/` and
 * `browser/`.
 *
 * Nobody walks that code to find what it implements (§1.1, 5): the app's two folders are
 * `import.meta.glob`, and Vite is the one that lists them — in dev it also invalidates the root
 * when a file appears. A library's folders are compiled files of a package, listed by name.
 *
 * Each file is loaded IN SEQUENCE, and the registry is told before each one which folder it
 * comes from: that is what lets a slot refuse a second implementation, or one in the wrong
 * folder, naming both files (§3.12). `ready` rejects with that error, and whoever needs the
 * implementations awaits it: the dispatcher, the render of a page, the prerender.
 *
 * The server root also imports every `fudic:<id>` of the project, so a function nobody
 * implemented still has a contract — and is a 404 that says what is missing, not an unknown URL.
 * The browser loads only `browser`: `src/server` never reaches a client bundle.
 *
 * A root never empties the registry. An app with languages has one root per locale, each with
 * its own `fudic:<id>` and its handlers compiled for it, so `t` and `locale` there are that
 * locale's (*decided while implementing*); they load in turn, never interleaved. A dev reload
 * evaluates the root again with fresh contracts, and the slots it fills are new ones.
 */

import type { ApiLibrary } from './api-modules.js';
import { API_SCHEME, libraryFiles } from './api-modules.js';

/** The two roots, by side. */
export const SERVER_ROOT_ID = `${API_SCHEME}$root/server`;
export const BROWSER_ROOT_ID = `${API_SCHEME}$root/browser`;
/** What the host plugin resolves a root to: `<root>/fudic-root.<side>.js`, never on disk. */
export const ROOT_FILE_PREFIX = 'fudic-root.';

export interface RootInput {
  readonly side: 'server' | 'browser';
  /** The app's folders, relative to its root: `src/server`, `src/browser`. */
  readonly folders: { readonly server: string; readonly browser: string };
  readonly libraries: readonly ApiLibrary[];
  /** The `<id>` the server root imports so every function has its contract. */
  readonly ids: readonly string[];
}

/** One folder's files as the root loads them: `[side, { label: () => import(…) }]`. */
const glob = (folder: string): string =>
  `import.meta.glob(${JSON.stringify([`/${folder}/**/*.{ts,js}`, `!/${folder}/**/*.d.ts`, `!/${folder}/**/*.{test,spec}.{ts,js}`])})`;

export function emitRoot(input: RootInput): string {
  const sides = input.side === 'server' ? (['browser', 'server'] as const) : (['browser'] as const);
  const lines = [`// Generated by fudic: the implementations of the ${input.side}. Do not edit.`];
  lines.push("import { inTurn, loadingFile, setFolders, takeRefusal } from '@fudic/http/contract';");
  if (input.side === 'server') {
    lines.push("import { contractsHandler } from '@fudic/http/contract/server';");
    for (const id of input.ids) lines.push(`import ${JSON.stringify(`${API_SCHEME}${id}`)};`);
    // Before any implementation is loaded: an error thrown in a handler names the `.ts` of
    // `src/server` and its line, and not the bundle the build made of it (SDD-60 §4.6).
    lines.push('globalThis.process?.setSourceMapsEnabled?.(true);');
  }
  lines.push('', 'const folders = [');
  for (const side of sides) {
    for (const lib of input.libraries) {
      const files = libraryFiles(`${lib.dir}/${lib[side]}`);
      const entries = files.map((file) => `${JSON.stringify(`${lib.name}${file.slice(lib.dir.length)}`)}: () => import(${JSON.stringify(file)})`);
      if (entries.length > 0) lines.push(`  [${JSON.stringify(side)}, { ${entries.join(', ')} }],`);
    }
    lines.push(`  [${JSON.stringify(side)}, ${glob(input.folders[side])}],`);
  }
  lines.push(
    '];',
    '',
    'async function load() {',
    `  setFolders(${JSON.stringify(input.folders)});`,
    '  try {',
    '    for (const [side, files] of folders) {',
    '      for (const [file, imported] of Object.entries(files)) {',
    "        loadingFile(side, file.replace(/^\\//u, ''));",
    // The registry's own refusal when it made the import fail: the preload helper a bundler
    // wraps an `import()` in may have hidden it behind an error of its own.
    '        await imported().catch((error) => {',
    '          throw takeRefusal() ?? error;',
    '        });',
    '      }',
    '    }',
    '  } finally {',
    '    loadingFile(undefined);',
    '  }',
    '}',
    '',
    '/** Every implementation registered, or the error of the one that could not be. */',
    'export const ready = inTurn(load);',
    '// Handled here so a failure nobody awaited yet is not an unhandled rejection.',
    'ready.catch(() => undefined);',
  );
  if (input.side === 'server') {
    lines.push(
      '',
      '/** The handler of every function of the project, once the implementations are in. */',
      'export function handler(options) {',
      '  const handle = contractsHandler(options);',
      '  return async (request) => {',
      '    await ready;',
      '    return handle(request);',
      '  };',
      '}',
    );
  }
  return `${lines.join('\n')}\n`;
}
