/**
 * `.fudic/edge/server.mjs` (SDD-81 §3.10): the app, as `createServer` of `@fudic/server` takes
 * it. Preview mounts it, and so does any adapter, with the prerendered pages of `outDir`:
 *
 *     import { createServer } from '@fudic/server';
 *     import { createApp, config } from './.fudic/edge/server.mjs';
 *     const server = createServer(createApp({ prerendered }), { ...config, secret });
 *
 * Every module it reaches is imported with a fixed text, so a bundler of an adapter follows them;
 * nothing here reads the disk.
 */

import type { ServeConfig } from '@fudic/config';

export interface ServerModuleInput {
  readonly base: string;
  readonly locales: readonly string[];
  /** The document CSP with its `{nonce}`. */
  readonly csp: string;
  /** Extra headers of the app's own static files, by path without `base`. */
  readonly statics: Readonly<Record<string, Readonly<Record<string, string>>>>;
  /** Each route, most specific first: its pattern, its hints, and its edge chunk when it has one. */
  readonly routes: readonly { readonly pattern: string; readonly hints: readonly string[]; readonly file?: string }[];
  /** `_error.fud` per locale (`''` in an app with one), with its edge chunk. */
  readonly errorPages: readonly { readonly locale: string; readonly file: string }[];
  /** The error page's hints: one for the app. */
  readonly errorHints: readonly string[];
  /** The file that exports the server root's `handler`, when the app has functions. */
  readonly functions?: string;
  readonly config: ServeConfig;
  /**
   * The workbench's own build (SDD-82 §4.7): the module says so, and the preview that serves it
   * with the bench installed answers the bench's criteria.
   */
  readonly bench?: boolean;
}

const relative = (file: string): string => JSON.stringify(`./${file}`);

export function emitServerModule(input: ServerModuleInput): string {
  const routes = input.routes.map(
    (r) =>
      `  { pattern: ${JSON.stringify(r.pattern)}, hints: ${JSON.stringify(r.hints)}, load: ${r.file === undefined ? 'undefined' : `() => import(${relative(r.file)})`} },`,
  );
  const pages = input.errorPages.map((p) => `  ${JSON.stringify(p.locale)}: () => import(${relative(p.file)}),`);
  const app = [
    `    base: ${JSON.stringify(input.base)},`,
    '    locales: LOCALES,',
    `    csp: ${JSON.stringify(input.csp)},`,
    `    statics: ${JSON.stringify(input.statics)},`,
    '    routes: () => table,',
    '    module: (pattern) => {',
    '      const load = modules.get(pattern);',
    "      if (load === undefined) throw new Error(`no render module for ${pattern}`);",
    '      return load();',
    '    },',
    '    errorPage: async (locale) => {',
    "      const load = LOCALES.length < 2 ? ERROR_PAGES[''] : ERROR_PAGES[locale ?? LOCALES[0]];",
    `      return load === undefined ? null : { module: await load(), hints: ${JSON.stringify(input.errorHints)} };`,
    '    },',
    '    prerendered: io.prerendered,',
    ...(input.functions === undefined ? [] : ['    functions: handler,']),
  ];
  return [
    '// Generated by fudic: the app for `createServer` of `@fudic/server` (SDD-81 §3.10). Do not edit.',
    ...(input.functions === undefined ? [] : [`import { handler } from ${relative(input.functions)};`]),
    '',
    `const LOCALES = ${JSON.stringify(input.locales)};`,
    '',
    '/** The routes, most specific first. */',
    'const ROUTES = [',
    ...routes,
    '];',
    '',
    '/** `_error.fud` of each locale. */',
    'const ERROR_PAGES = {',
    ...pages,
    '};',
    '',
    "/** fudic.json's `serve`: what the server is told, unless whoever mounts it says otherwise. */",
    `export const config = ${JSON.stringify(input.config)};`,
    '',
    ...(input.bench === true ? ["/** Built by the workbench for its criteria: never deployed. */", 'export const bench = true;', ''] : []),
    '/** The app, given where its prerendered pages are. */',
    'export function createApp(io) {',
    '  const table = ROUTES.map((r) => ({ pattern: r.pattern, renders: r.load !== undefined, hints: async () => r.hints }));',
    '  const modules = new Map(ROUTES.filter((r) => r.load !== undefined).map((r) => [r.pattern, r.load]));',
    '  return {',
    ...app,
    '  };',
    '}',
    '',
  ].join('\n');
}
