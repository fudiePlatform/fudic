import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'vite';
import { beforeAll, describe, expect, it } from 'vitest';
import { fudic } from '@fudic/vite';
import { nodeReadIo, nodeWriteIo } from '../src/io.js';
import { workbenchOf, type ShowcaseKit } from '../src/plans/showcase.js';
import { parseFud } from '../src/parse.js';
import { run } from '../src/run.js';
import { captureStreams, MemoryFs, RecordingRunner } from './helpers.js';

const REPO = fileURLToPath(new URL('../../../', import.meta.url));
const WORKBENCH = join(REPO, 'packages/workbench');

type Cases = Readonly<Record<string, Readonly<Record<string, unknown>>>>;

/** The real workbench, as the project installed it: its build. */
let real: ShowcaseKit;
beforeAll(async () => {
  real = (await import(pathToFileURL(join(WORKBENCH, 'dist/index.js')).href)) as ShowcaseKit;
});

/** A workbench whose fixtures are the given cases, by component folder; a `null` one throws. */
function kit(cases: Readonly<Record<string, Cases | null>>, seen: string[] = []): (dir: string) => Promise<ShowcaseKit> {
  return (dir) => {
    seen.push(dir.replace(/\\/gu, '/'));
    return Promise.resolve({
      planShowcase: real.planShowcase,
      executeFixtures: (_root, files) => {
        const fixtures = new Map<string, Cases>();
        const diagnostics: { code: 'FUD0973'; severity: 'error'; message: string }[] = [];
        for (const file of files) {
          const tag = file.slice(file.lastIndexOf('/') + 1).replace(/\.fixture\.ts$/u, '');
          const one = cases[tag];
          if (one === null) diagnostics.push({ code: 'FUD0973', severity: 'error', message: `${file} threw: broken` });
          else fixtures.set(file, one ?? {});
        }
        return Promise.resolve({ fixtures, diagnostics } as unknown as Awaited<ReturnType<ShowcaseKit['executeFixtures']>>);
      },
    });
  };
}

interface Ran {
  readonly code: number;
  readonly out: string;
  readonly err: string;
}

async function cli(fs: MemoryFs, workbench: (dir: string) => Promise<ShowcaseKit>, ...argv: string[]): Promise<Ran> {
  const capture = captureStreams();
  const code = await run(argv, { readIo: fs, writeIo: fs, runner: new RecordingRunner(), streams: capture.streams, workbenchOf: workbench });
  return { code, out: capture.stdout(), err: capture.stderr() };
}

const W = '/w';
const SHOP = '/w/shop';
const MARK = '<!-- Generated by `fudic g showcase ui`. Run it again instead of editing this file. -->';

/** `fudic new shop --workspace --app web`, `g lib ui` and its `button` and `card`. */
async function shop(): Promise<MemoryFs> {
  const fs = new MemoryFs({}, W);
  const none = kit({});
  expect((await cli(fs, none, 'new', 'shop', '--workspace', '--app', 'web', '--cwd', W)).code).toBe(0);
  expect((await cli(fs, none, 'g', 'lib', 'ui', '--cwd', SHOP)).code).toBe(0);
  expect((await cli(fs, none, 'g', 'component', 'button', '--project', 'ui', '--cwd', SHOP)).code).toBe(0);
  expect((await cli(fs, none, 'g', 'component', 'card', '--project', 'ui', '--cwd', SHOP)).code).toBe(0);
  return fs;
}

const CASES = {
  'ui-button': { primary: { variant: 'primary', $content: 'Save' }, 'titulo-largo': { variant: 'ghost' } },
  'ui-card': { base: { title: 'Tarjeta', $content: '<p>body</p>' } },
};

const PAGES = 'shop/apps/showcase/src/routes';

describe('criterion 6: g showcase ui in a workspace (the plan)', () => {
  it('creates the app that uses the library, a page per component and the index as its home', async () => {
    const fs = await shop();
    const seen: string[] = [];
    const { code, out } = await cli(fs, kit(CASES, seen), 'g', 'showcase', 'ui', '--cwd', SHOP);
    expect(out).not.toMatch(/FUD\d{4}/u);
    expect(code).toBe(0);
    // The workbench is the one the LIBRARY installed: it runs the library's fixtures.
    expect(seen.map((dir) => dir.replace(/^[A-Z]:/u, ''))).toEqual(['/w/shop/libs/ui']);

    const pkg = JSON.parse(fs.at('shop/apps/showcase/package.json')) as { dependencies: Record<string, string> };
    expect(pkg.dependencies).toMatchObject({ '@shop/ui': 'workspace:*' });
    expect(fs.paths().filter((path) => path.startsWith(`${PAGES}/`) && !path.endsWith('.test.ts'))).toEqual([
      `${PAGES}/index.fud`,
      `${PAGES}/ui-button.fud`,
      `${PAGES}/ui-card.fud`,
    ]);

    const button = fs.at(`${PAGES}/ui-button.fud`);
    expect(button.split('\n').slice(0, 3)).toEqual([MARK, '<link rel="layout" href="../layouts/_layout.fud">', '<link rel="component" href="@shop/ui/ui-button.fud">']);
    expect(button).toContain("import cases from '@shop/ui/ui-button.fixture';");
    expect(button).toContain('const tituloLargo = cases["titulo-largo"];');
    expect(button).toContain('<ui-button .variant=@primary.variant>Save</ui-button>');
    expect(fs.at(`${PAGES}/ui-card.fud`)).toContain('<ui-card .title=@base.title><p>body</p></ui-card>');

    const index = fs.at(`${PAGES}/index.fud`);
    expect(index.startsWith(`${MARK}\n`)).toBe(true);
    expect(index).toMatch(/<li><a href="\/[^"]*ui-button">ui-button<\/a><\/li>\n {2}<li><a href="\/[^"]*ui-card">ui-card<\/a><\/li>/u);
  });

  it('--app names the app, and the mark says so', async () => {
    const fs = await shop();
    const { code } = await cli(fs, kit(CASES), 'g', 'showcase', 'ui', '--app', 'gallery', '--cwd', SHOP);
    expect(code).toBe(0);
    expect(fs.at('shop/apps/gallery/src/routes/ui-card.fud').split('\n')[0]).toBe(
      '<!-- Generated by `fudic g showcase ui --app gallery`. Run it again instead of editing this file. -->',
    );
  });

  it('into an app that exists and does not use the library, adds it; its own home page is FUD0443', async () => {
    const fs = await shop();
    const { code, out } = await cli(fs, kit(CASES), 'g', 'showcase', 'ui', '--app', 'web', '--cwd', SHOP);
    expect(code).toBe(1);
    expect(out).toContain('FUD0443');
    expect(out).toContain('index.fud');
    expect(fs.exists(`${SHOP}/apps/web/src/routes/ui-card.fud`)).toBe(false);
  });

  it('a case with a signal prop goes through a host in src/components/showcase of the app (criterion 7)', async () => {
    const fs = await shop();
    const signal = Object.assign(() => 3, { set: () => undefined });
    const { code } = await cli(fs, kit({ ...CASES, 'ui-card': { live: { title: signal } } }), 'g', 'showcase', 'ui', '--cwd', SHOP);
    expect(code).toBe(0);
    const host = fs.at('shop/apps/showcase/src/components/showcase/showcase-ui-card-live.fud');
    expect(host.split('\n')[0]).toBe(MARK);
    expect(host).toContain('<link rel="component" href="@shop/ui/ui-card.fud">');
    expect(host).toContain('const title = signal(3);');
    expect(fs.at(`${PAGES}/ui-card.fud`)).toContain('<link rel="component" href="../components/showcase/showcase-ui-card-live.fud">');
  });

  it('--dry-run --json prints the plan and writes nothing', async () => {
    const fs = await shop();
    const before = fs.paths();
    const { code, out } = await cli(fs, kit(CASES), 'g', 'showcase', 'ui', '--dry-run', '--json', '--cwd', SHOP);
    expect(code).toBe(0);
    const plan = JSON.parse(out) as { changes: { path: string }[] };
    expect(plan.changes.map((change) => change.path)).toEqual(expect.arrayContaining(['apps/showcase/src/routes/ui-button.fud', 'apps/showcase/src/routes/index.fud']));
    expect(fs.paths()).toEqual(before);
  });
});

describe('criterion 8: run it again', () => {
  it('with nothing changed writes nothing; a new case rewrites only its page, without --force', async () => {
    const fs = await shop();
    expect((await cli(fs, kit(CASES), 'g', 'showcase', 'ui', '--cwd', SHOP)).code).toBe(0);
    const snapshot = new Map(fs.paths().map((path) => [path, fs.at(path)]));

    expect((await cli(fs, kit(CASES), 'g', 'showcase', 'ui', '--cwd', SHOP)).code).toBe(0);
    for (const [path, contents] of snapshot) expect(fs.at(path), path).toBe(contents);
    expect(fs.paths()).toEqual([...snapshot.keys()]);

    const grown = { ...CASES, 'ui-card': { ...CASES['ui-card'], vacia: { title: '' } } };
    expect((await cli(fs, kit(grown), 'g', 'showcase', 'ui', '--cwd', SHOP)).code).toBe(0);
    const changed = fs.paths().filter((path) => snapshot.get(path) !== fs.at(path));
    expect(changed).toEqual([`${PAGES}/ui-card.fud`]);
    expect(fs.at(`${PAGES}/ui-card.fud`)).toContain('<h2>vacia</h2>');
  });

  it('a new component with a fixture adds its page; one that loses its fixture loses it', async () => {
    const fs = await shop();
    expect((await cli(fs, kit(CASES), 'g', 'showcase', 'ui', '--cwd', SHOP)).code).toBe(0);

    expect((await cli(fs, kit({}), 'g', 'component', 'badge', '--project', 'ui', '--cwd', SHOP)).code).toBe(0);
    fs.remove(`${SHOP}/libs/ui/src/components/ui-card/ui-card.fixture.ts`);
    const { code } = await cli(fs, kit({ ...CASES, 'ui-badge': { base: {} } }), 'g', 'showcase', 'ui', '--cwd', SHOP);
    expect(code).toBe(0);
    expect(fs.exists(`${SHOP}/apps/showcase/src/routes/ui-badge.fud`)).toBe(true);
    expect(fs.exists(`${SHOP}/apps/showcase/src/routes/ui-card.fud`)).toBe(false);
    expect(fs.at(`${PAGES}/index.fud`)).toContain('ui-badge');
    expect(fs.at(`${PAGES}/index.fud`)).not.toContain('ui-card');
  });
});

