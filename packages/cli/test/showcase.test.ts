/**
 * `fudic g showcase [<library>]` (SDD-66 §3.2, §4.2) — criteria 6, 8–11 through the CLI.
 *
 * Over a `MemoryFs`, with the workbench the project would install injected: its real
 * `planShowcase` (from its build) and an `executeFixtures` that answers the cases a test names,
 * since a fixture in memory cannot be run. Criterion 6 runs end to end over a copy of
 * `examples/workspace`: the real workbench executes the real fixture and the app it writes builds.
 */

