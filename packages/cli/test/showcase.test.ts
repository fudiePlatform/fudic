const ssrDist = join(REPO, 'packages/ssr/dist/index.js');
const transportDist = join(REPO, 'packages/transport/dist/index.js');
const coreDist = join(REPO, 'packages/core/dist/index.js');

describe('criterion 6: g showcase ui over examples/workspace builds, each case painted', () => {
  let output: { fileName: string; source?: string | Uint8Array }[];
  let ws: string;

  beforeAll(async () => {
    ws = join(mkdtempSync(join(tmpdir(), 'fudic-showcase-ws-')), 'workspace');
    const from = join(REPO, 'examples/workspace');
    cpSync(from, ws, {
      recursive: true,
      filter: (path) => !/[\\/](node_modules|dist|\.fudic|tests)([\\/]|$)/u.test(path.slice(from.length)),
    });
    // In the repository the example is a member of the repository's own workspace and leans on
    // its root. On its own, as a user has it, it has the root `fudic new --workspace` writes: its
    // `pnpm-workspace.yaml`, and the `tsconfig.base.json` and globals a new app extends.
    const root = new MemoryFs({}, W);
    expect((await cli(root, kit({}), 'new', 'shop', '--workspace', '--app', 'web', '--cwd', W)).code).toBe(0);
    for (const file of ['pnpm-workspace.yaml', 'tsconfig.base.json', 'fudic-globals.d.ts']) writeFileSync(join(ws, file), root.at(`shop/${file}`));
    // A second case with content, as an author adds one: the page must paint both.
    const fixture = join(ws, 'libs/ui/src/components/ui-card/ui-card.fixture.ts');
    writeFileSync(fixture, readFileSync(fixture, 'utf8').replace("base: { title: 'Tarjeta' },", "base: { title: 'Tarjeta' },\n  'con-lista': { title: 'Con lista', $content: '<ul><li>uno</li></ul>' },"));
    // What the install links: the library's workbench and its own dependencies.
    const link = (dir: string, name: string, target: string): void => {
      mkdirSync(join(dir, 'node_modules', ...name.split('/').slice(0, -1)), { recursive: true });
      symlinkSync(target, join(dir, 'node_modules', name), 'junction');
    };
    for (const name of ['core', 'dom', 'ssr', 'terms', 'workbench']) link(join(ws, 'libs/ui'), `@fudic/${name}`, join(REPO, 'packages', name));
    link(join(ws, 'libs/ui'), '@fudic/example-guia', join(ws, 'libs/guia'));

    const capture = captureStreams();
    const code = await run(['g', 'showcase', 'ui', '--cwd', ws], { readIo: nodeReadIo(), writeIo: nodeWriteIo(), runner: new RecordingRunner(), streams: capture.streams });
    if (code !== 0) throw new Error(`fudic g showcase ui exited ${code}:\n${capture.stdout()}${capture.stderr()}`);

    link(join(ws, 'apps/showcase'), '@fudic/example-ui', join(ws, 'libs/ui'));
    const result = (await build({
      root: join(ws, 'apps/showcase'),
      logLevel: 'info',
      configFile: false,
      resolve: { alias: { '@fudic/ssr': ssrDist, '@fudic/transport': transportDist, '@fudic/core': coreDist } },
      plugins: [fudic()],
      build: { write: false, minify: false },
    })) as unknown as { output: { fileName: string; source?: string | Uint8Array }[] };
    output = result.output;
  }, 240_000);

  const html = (name: string): string => {
    const file = output.find((one) => one.fileName === name);
    expect(file, output.map((one) => one.fileName).join(', ')).toBeDefined();
    return String(file!.source);
  };

  it('writes apps/showcase with one page per component of libs/ui with a fixture, and its index', () => {
    const pages = join(ws, 'apps/showcase/src/routes');
    // The header `g page` writes in that app: its layout.
    expect(readFileSync(join(pages, 'ui-card.fud'), 'utf8').split('\n')[1]).toBe('<link rel="layout" href="../layouts/_layout.fud">');
    expect(readFileSync(join(pages, 'ui-card.fud'), 'utf8')).toContain("import cases from '@fudic/example-ui/ui-card.fixture';");
    expect(readFileSync(join(pages, 'index.fud'), 'utf8')).toContain('>ui-card</a>');
  });

  it('the page of ui-card paints each case with its props and its content', () => {
    const page = html('ui-card/index.html');
    expect(page).toContain('<h2>base</h2>');
    expect(page).toContain('<h2>con-lista</h2>');
    expect(page.match(/<ui-card><template shadowrootmode=/gu)).toHaveLength(2);
    expect(page).toContain('Tarjeta');
    expect(page).toContain('Con lista');
    expect(page).toContain('<ul><li>uno</li></ul>');
  });

  it('the index links the page', () => {
    expect(html('index.html')).toMatch(/<a href="[^"]*ui-card">ui-card<\/a>/u);
  });
});
