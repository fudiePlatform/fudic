describe('criterion 11: an app on its own', () => {
  it('g showcase writes under src/routes/showcase, with relative hrefs, and its index links /showcase/<tag>', async () => {
    const fs = new MemoryFs({}, W);
    expect((await cli(fs, kit({}), 'new', 'solo', '--no-install', '--no-git', '--cwd', W)).code).toBe(0);
    expect((await cli(fs, kit({}), 'g', 'component', 'card', '--cwd', `${W}/solo`)).code).toBe(0);
    const tag = fs.paths().find((path) => /^solo\/src\/components\/[^/]+\/[^/]+\.fixture\.ts$/u.test(path))!.split('/')[3]!;

    const seen: string[] = [];
    const { code } = await cli(fs, kit({ [tag]: { base: { title: 'T' } } }, seen), 'g', 'showcase', '--cwd', `${W}/solo`);
    expect(code).toBe(0);
    expect(seen.map((dir) => dir.replace(/^[A-Z]:/u, ''))).toEqual(['/w/solo']);

    const page = fs.at(`solo/src/routes/showcase/${tag}.fud`);
    expect(page.split('\n')[0]).toBe('<!-- Generated by `fudic g showcase`. Run it again instead of editing this file. -->');
    expect(page).toContain(`<link rel="component" href="../../components/${tag}/${tag}.fud">`);
    expect(page).toContain(`import cases from '../../components/${tag}/${tag}.fixture';`);
    expect(fs.at('solo/src/routes/showcase/index.fud')).toContain(`<li><a href="/showcase/${tag}">${tag}</a></li>`);
    // The app's own home page is not the showcase's.
    expect(fs.at('solo/src/routes/index.fud').startsWith('<!--')).toBe(false);
  });

  it('in an app with no layout, each page is a whole document that is still a page', async () => {
    const fs = new MemoryFs({}, W);
    expect((await cli(fs, kit({}), 'new', 'bare', '--no-layout', '--no-install', '--no-git', '--cwd', W)).code).toBe(0);
    expect((await cli(fs, kit({}), 'g', 'component', 'card', '--cwd', `${W}/bare`)).code).toBe(0);
    const tag = fs.paths().find((path) => /^bare\/src\/components\/[^/]+\/[^/]+\.fixture\.ts$/u.test(path))!.split('/')[3]!;
    const { code } = await cli(fs, kit({ [tag]: { base: { title: 'T' } } }), 'g', 'showcase', '--cwd', `${W}/bare`);
    expect(code).toBe(0);
    for (const file of [`${tag}.fud`, 'index.fud']) {
      const parsed = parseFud(fs.at(`bare/src/routes/showcase/${file}`));
      expect(parsed.diagnostics.filter((d) => d.severity === 'error'), file).toEqual([]);
      expect(parsed.doc.type, file).toBe('page-document');
    }
  });
});

