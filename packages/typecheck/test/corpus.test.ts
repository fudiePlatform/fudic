/**
 * The repository writes the portable view, through the build's channel (SDD-61 criteria 1, 22 and
 * 33): every project of the repository, checked as the build checks it — the semantic pass with
 * its server cut into the stores, and the typed pass over the program — gives no code of the
 * view. `examples/basic/src/routes/vista.fud`, the catalog of what the view may write, is one of
 * its files (criterion 1).
 *
 * A project is a folder with a `fudic.json`, or a folder of fixtures a package's tests read as
 * one. The list is written out, and a test holds it to the repository: a tracked `.fud` outside
 * every root fails by its name, so nothing new escapes the net.
 *
 * The `.fudapi` contracts of an example are generated by its build (`.fudic/api`); without one
 * the names they bring are unresolved, the typed pass has nothing to ask of them, and this net is
 * only as wide as the semantic pass. `pnpm build` runs before `pnpm test`.
 */

import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { createProjectChecker, toPosix, type CheckReport } from '../src/index.js';

/** The repository's root, with its last `/`. */
const REPO = `${toPosix(fileURLToPath(new URL('../../../', import.meta.url))).replace(/\/$/u, '')}/`;

/** Every project of the repository that holds a `.fud`, by its folder from the root. */
const ROOTS = [
  'examples/basic',
  'examples/i18n',
  'examples/fudapi-editor',
  'examples/workspace/apps/admin',
  'examples/workspace/apps/tienda',
  'examples/workspace/libs/guia',
  'examples/workspace/libs/ui',
  'packages/cli/templates',
  'packages/compiler/fixtures',
  'packages/compiler/test/fixtures',
  'packages/formatter/fixtures',
  'packages/language-core/fixtures',
  'packages/language-server/fixtures',
  'packages/testing/test/app',
  'packages/testing/test/bare-app',
  'packages/testing/test/conformance',
  'packages/testing/test/fixtures',
  'packages/vscode/fixtures',
  'packages/workbench/test/fixtures/project',
] as const;

/**
 * Not a project: the pages the workbench writes, as its test expects them, for a component at
 * `C:/proj` (criterion 22). They are checked inside the project they name, below.
 */
const BENCH = 'packages/workbench/test/expected/app-card';

/** Where the view gives its codes on purpose (criterion 32), held to its comments elsewhere. */
const ERRORS = 'examples/vista-errores';

/** The codes of the view: SDD-51's range with the template's `$` (FUD0461), and SDD-61's. */
const VIEW = /^FUD09[01]\d$|^FUD0461$|^FUD11[45]\d$/u;

/** The view's codes in `report`, as `file: CODE text`, the file from `root`. */
function viewProblems(report: CheckReport, root: string): readonly string[] {
  return report.problems
    .filter((p) => VIEW.test(p.code))
    .map((p) => {
      const file = toPosix(p.file);
      return `${file.slice(root.length + 1)}: ${p.code} ${readFileSync(file, 'utf8').slice(p.span.start, p.span.end)}`;
    });
}

describe('every .fud of the repository is in a project of the net', () => {
  it('outside experiments/, each tracked .fud sits under one of the roots', () => {
    const tracked = execFileSync('git', ['ls-files', '*.fud'], { cwd: REPO, encoding: 'utf8' }).split('\n');
    const loose = tracked.filter(
      (path) =>
        path !== '' &&
        !path.startsWith('experiments/') &&
        ![...ROOTS, BENCH, ERRORS].some((root) => path.startsWith(`${root}/`)),
    );
    expect(loose).toEqual([]);
  });
});

describe('the repository writes the portable view (criteria 1 and 33)', () => {
  for (const root of ROOTS) {
    it(root, { timeout: 120_000 }, () => {
      const at = `${REPO}${root}`;
      expect(viewProblems(createProjectChecker({ root: at }).check(), at)).toEqual([]);
    });
  }
});

describe('the pages the workbench writes compile in the project they name (criterion 22)', () => {
  it('each expected page of app-card, with `C:/proj` the folder of examples/basic it names', { timeout: 120_000 }, () => {
    // The component and its fixtures, as examples/basic has them, in a project of their own: the
    // pages import a module of data by an absolute path, and the cut follows it to read it.
    const root = toPosix(mkdtempSync(join(tmpdir(), 'fudic-bench-corpus-')));
    const components = `${REPO}examples/basic/src/components`;
    mkdirSync(`${root}/src/components`, { recursive: true });
    mkdirSync(`${root}/bench`);
    for (const file of ['app-card.fud', 'app-badge.fud', 'app-card.fixture.ts']) {
      copyFileSync(`${components}/${file}`, `${root}/src/components/${file}`);
    }
    writeFileSync(`${root}/fudic.json`, JSON.stringify({ id: 'bench', kind: 'app', prefix: 'app' }));
    writeFileSync(
      `${root}/tsconfig.json`,
      JSON.stringify({ compilerOptions: { strict: true, skipLibCheck: true, module: 'ESNext', moduleResolution: 'bundler' } }),
    );
    const pages = readdirSync(`${REPO}${BENCH}`);
    for (const page of pages) {
      writeFileSync(`${root}/bench/${page}`, readFileSync(`${REPO}${BENCH}/${page}`, 'utf8').replaceAll('C:/proj', root));
    }
    expect(pages.length).toBeGreaterThan(1);
    expect(viewProblems(createProjectChecker({ root }).check(), root)).toEqual([]);
  });
});
