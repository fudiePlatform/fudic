/**
 * SDD-60 §3.11, §4.9 and criteria 27 (touching a rule's `.fudapi` revalidates the one that uses
 * it) and 30 (saving a `.fudapi` updates its `.d.ts`, and the TypeScript of a file of
 * `src/server` that imports it sees the change).
 */

import { mkdirSync, mkdtempSync, readFileSync, existsSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';
import { emitDeclarations } from '@fudic/api';
import { toPosix } from '@fudic/typecheck';
import type { LanguageServicePluginInstance } from '@volar/language-service';
import { CancellationToken, type Diagnostic } from 'vscode-languageserver-protocol';
import { TextDocument } from 'vscode-languageserver-textdocument';
import { URI } from 'vscode-uri';
import { nodeApiFs } from '../../src/fudapi/fs.js';
import { ApiHost } from '../../src/fudapi/host.js';
import { createFudapiService } from '../../src/fudapi/service.js';
import { RequestStats } from '../../src/stats.js';
import { fakeServiceContext } from '../_lsp.js';
import { APP, FILES, ROOT, SRC, world } from './_api.js';

const TYPES = `${APP}/.fudic/api`;

describe('generate (§3.11, §4.9)', () => {
  it('writes the .d.ts of every .fudapi of the project, its dependencies included', () => {
    const { host, fs } = world();
    const written = host.generate(APP);
    expect([...written].sort()).toEqual(
      [
        `${TYPES}/@fudic/dev/dev.d.ts`,
        `${TYPES}/@fudic/forms/patterns.d.ts`,
        `${TYPES}/@fudic/forms/rules.d.ts`,
        `${TYPES}/@fudic/http/middlewares.d.ts`,
        `${TYPES}/middlewares/auth.d.ts`,
        `${TYPES}/types/person.d.ts`,
      ].sort(),
    );
    expect(fs.writes).toEqual(written);
    const person = fs.readFile(`${TYPES}/types/person.d.ts`)!;
    expect(person).toContain(`declare module "fudic:types/person"`);
    expect(person).toContain('export interface Person { readonly name: string }');
    expect(person).toContain("export type Role = 'admin' | 'user';");
  });

  it('writes only what changed: nothing the second time', () => {
    const { host, fs } = world();
    host.generate(APP);
    expect(host.generate(APP)).toEqual([]);
    expect(fs.writes).toHaveLength(6);
  });

  it('a change rewrites the file and whoever depends on it, nobody else', () => {
    const files = { ...FILES, [`${SRC}/components/user-form.fudapi`]: 'put save\n  use auth\n' };
    const { host, fs } = world({ files });
    host.generate(APP);
    const before = fs.readFile(`${TYPES}/components/user-form.d.ts`)!;
    expect(before).toContain('& import("fudic:middlewares/auth").AuthAdds');

    // auth stops adding to ctx: its own types change, and so do those of the function using it.
    fs.writeFile(`${SRC}/middlewares/auth.fudapi`, 'middleware auth\n  server\n');
    fs.writes.length = 0;
    host.invalidate();
    expect([...host.generate(APP)].sort()).toEqual([`${TYPES}/components/user-form.d.ts`, `${TYPES}/middlewares/auth.d.ts`]);
    expect(fs.readFile(`${TYPES}/components/user-form.d.ts`)).not.toContain('AuthAdds');
  });

  it('takes the text of a file open in the editor, not the disk’s', () => {
    const { host, fs } = world({ open: { [`${SRC}/types/person.fudapi`]: 'type Person\n  name  str\n  age  u8\n' } });
    host.generate(APP);
    expect(fs.readFile(`${TYPES}/types/person.d.ts`)).toContain('readonly age: number');
  });

  it('knows a route sibling: its params and its pattern reach the types', () => {
    const files = { ...FILES, [`${SRC}/routes/blog/[slug].fudapi`]: 'put save /:id\n  id  i32\n' };
    const { host, fs } = world({ files });
    host.generate(APP);
    expect(fs.readFile(`${TYPES}/routes/blog/[slug].d.ts`)).toContain('FnContext<{ readonly slug: string; readonly id: number }');
  });

  it('an index route is the folder; an index folder stays in the pattern', () => {
    const files = {
      ...FILES,
      [`${SRC}/routes/blog/index.fud`]: '<app-blog></app-blog>\n',
      [`${SRC}/routes/blog/index.fudapi`]: 'get list\n',
      [`${SRC}/routes/index/[id].fud`]: '<app-x></app-x>\n',
      [`${SRC}/routes/index/[id].fudapi`]: 'get one\n',
    };
    const { host } = world({ files });
    expect(host.load(`${SRC}/routes/blog/index.fudapi`, '').context).toEqual({ route: { params: [], pattern: '/blog' } });
    expect(host.load(`${SRC}/routes/index/[id].fudapi`, '').context).toEqual({ route: { params: ['id'], pattern: '/index/:id' } });
  });

  it('a .fudapi listed but unreadable is an empty contract, never a throw', () => {
    const { host, fs } = world({ files: { ...FILES, [`${SRC}/locked.fudapi`]: undefined } });
    expect(host.generate(APP)).toContain(`${TYPES}/locked.d.ts`);
    expect(fs.readFile(`${TYPES}/locked.d.ts`)).toBe('// Generated by fudic from locked.fudapi. Do not edit.\ndeclare module "fudic:locked" {\n\n}\n');
  });

  it('writes exactly what emitDeclarations gives', () => {
    const { host, fs } = world();
    host.generate(APP);
    const { source, index, context } = host.load(`${SRC}/types/person.fudapi`, FILES[`${SRC}/types/person.fudapi`]!);
    expect(fs.readFile(`${TYPES}/types/person.d.ts`)).toBe(emitDeclarations(source, index, context));
  });
});

describe('forget', () => {
  it('removes the types of a .fudapi that is gone', () => {
    const { host, fs } = world();
    host.generate(APP);
    host.forget(`${SRC}/types/person.fudapi`);
    expect(fs.removed).toEqual([`${TYPES}/types/person.d.ts`]);
    expect(fs.readFile(`${TYPES}/types/person.d.ts`)).toBeUndefined();
  });

  it('a file outside src/ is named by its file name', () => {
    const { host, fs } = world();
    host.forget(`${APP}/elsewhere/loose.fudapi`);
    expect(fs.removed).toEqual([`${TYPES}/loose.d.ts`]);
  });
});

describe('projects', () => {
  it('the projects with a .fudapi of their own under src/', () => {
    const files = {
      ...FILES,
      [`${ROOT}/other/package.json`]: '{}',
      [`${ROOT}/other/src/a.fudapi`]: 'type A\n  x  str\n',
      // Only a dependency's: not a project of the workspace.
      [`${ROOT}/lib/package.json`]: '{}',
      [`${ROOT}/lib/fudapi/b.fudapi`]: 'type B\n  x  str\n',
    };
    expect([...world({ files }).host.projects()].sort()).toEqual([APP, `${ROOT}/other`]);
  });

  it('none in a workspace without contracts; each root on its own', () => {
    expect(world({ files: { [`${ROOT}/package.json`]: '{}' } }).host.projects()).toEqual([]);
    const files = { '/a/package.json': '{}', '/a/src/x.fudapi': '', '/b/package.json': '{}', '/b/src/y.fudapi': '' };
    expect(world({ files, roots: ['/a', '/b'] }).host.projects()).toEqual(['/a', '/b']);
  });
});

describe('criterion 27: touching the .fudapi of a rule revalidates the one that uses it', () => {
  const USER = `${SRC}/components/alta.fudapi`;
  const USES = 'form alta\n  nif  str\n    nif-letter\n';
  const RULE = 'rule nif-letter\n  on field str\n  runs both\n  fails nif-letter\n';

  async function diagnosticsOf(host: ApiHost): Promise<readonly string[]> {
    const uri = URI.file(USER);
    const service: LanguageServicePluginInstance = createFudapiService({ host, stats: new RequestStats() }).create(
      fakeServiceContext({}, (u) => (u.toString() === uri.toString() ? [uri, 'root'] : undefined)),
    );
    const found = (await service.provideDiagnostics?.(TextDocument.create(uri.toString(), 'fudapi', 1, USES), CancellationToken.None)) as Diagnostic[];
    return found.map((d) => `${String(d.code)} ${d.message}`);
  }

  it('a rule that appears, or goes, changes the diagnostics of its user once the files are read again', async () => {
    const { host, fs } = world({ files: { ...FILES, [USER]: USES } });
    expect((await diagnosticsOf(host)).join()).toContain('FUD1080');

    fs.writeFile(`${SRC}/rules/nif.fudapi`, RULE);
    host.invalidate();
    expect(await diagnosticsOf(host)).toEqual([]);

    // Its fails renamed: the user is fine still; the rule taking a parameter is not.
    fs.writeFile(`${SRC}/rules/nif.fudapi`, `${RULE.replace('fails nif-letter', 'n  u8\n  fails nif-letter n')}`);
    host.invalidate();
    expect((await diagnosticsOf(host)).join()).toContain('FUD1084');
  });
});

describe('criterion 30: saving a .fudapi updates its .d.ts, and TypeScript sees it', () => {
  /** An app on disk: a contract, and a handler in src/server that reads a field of its type. */
  function app(): string {
    const root = toPosix(mkdtempSync(join(tmpdir(), 'fudapi-gen-')));
    mkdirSync(`${root}/src/server`, { recursive: true });
    mkdirSync(`${root}/src/types`, { recursive: true });
    writeFileSync(`${root}/package.json`, '{ "name": "app" }');
    writeFileSync(`${root}/src/types/person.fudapi`, 'type Person\n  name  str\n');
    writeFileSync(
      `${root}/src/server/greet.ts`,
      "import type { Person } from 'fudic:types/person';\nexport const greet = (p: Person): string => p.name;\n",
    );
    writeFileSync(
      `${root}/tsconfig.json`,
      JSON.stringify({
        compilerOptions: { strict: true, noEmit: true, module: 'ESNext', moduleResolution: 'bundler', target: 'ES2024', lib: ['ES2024'], types: [] },
        include: ['src/**/*.ts', '.fudic/api/**/*.d.ts'],
      }),
    );
    return root;
  }

  /** What `tsc -p` says about the app, as TypeScript reads its tsconfig. */
  function errors(root: string): readonly string[] {
    const config = ts.getParsedCommandLineOfConfigFile(`${root}/tsconfig.json`, {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} })!;
    const program = ts.createProgram(config.fileNames, config.options);
    return ts.getPreEmitDiagnostics(program).map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
  }

  it('the handler types against the generated module; the field renamed and saved, it does not', () => {
    const root = app();
    const host = new ApiHost({ fs: nodeApiFs(), roots: () => [root], open: () => undefined });
    expect(host.projects()).toEqual([root]);

    // Before the first generation there is no module to import.
    expect(errors(root).join()).toContain("Cannot find module 'fudic:types/person'");
    expect(host.generate(root)).toEqual([`${root}/.fudic/api/types/person.d.ts`]);
    expect(errors(root)).toEqual([]);

    writeFileSync(`${root}/src/types/person.fudapi`, 'type Person\n  fullName  str\n');
    host.invalidate();
    expect(host.generate(root)).toEqual([`${root}/.fudic/api/types/person.d.ts`]);
    expect(readFileSync(`${root}/.fudic/api/types/person.d.ts`, 'utf8')).toContain('readonly fullName: string');
    expect(errors(root).join()).toContain("Property 'name' does not exist on type 'Person'");

    host.forget(`${root}/src/types/person.fudapi`);
    expect(existsSync(`${root}/.fudic/api/types/person.d.ts`)).toBe(false);
  }, 120_000);
});

describe('nodeApiFs writes', () => {
  it('writes a file, creating its folders, and removes it; a missing one is no error', () => {
    const root = toPosix(mkdtempSync(join(tmpdir(), 'fudapi-fs-')));
    const fs = nodeApiFs();
    fs.writeFile(`${root}/a/b/c.d.ts`, 'x');
    expect(fs.readFile(`${root}/a/b/c.d.ts`)).toBe('x');
    fs.removeFile(`${root}/a/b/c.d.ts`);
    expect(fs.readFile(`${root}/a/b/c.d.ts`)).toBeUndefined();
    expect(() => fs.removeFile(`${root}/a/b/c.d.ts`)).not.toThrow();
  });

  it('a file that cannot be written or removed is left as it is, never a throw', () => {
    const root = toPosix(mkdtempSync(join(tmpdir(), 'fudapi-fs-')));
    writeFileSync(`${root}/file`, 'x');
    const fs = nodeApiFs();
    // A folder cannot be made under a file.
    expect(() => fs.writeFile(`${root}/file/inside.d.ts`, 'y')).not.toThrow();
    expect(fs.readFile(`${root}/file`)).toBe('x');
    // A folder is not removed as a file.
    mkdirSync(`${root}/folder`);
    expect(() => fs.removeFile(`${root}/folder`)).not.toThrow();
    expect(existsSync(`${root}/folder`)).toBe(true);
  });
});
